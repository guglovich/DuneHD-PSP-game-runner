/*
 * Пересчёт слова HI16 при релокации MIPS.
 *
 * Вынесено в отдельный заголовок не ради порядка, а ради проверки: гейт
 * `tools/check_reloc.sh` подключает ЭТОТ файл и проверяет его на настоящем
 * образе гостя. Раньше проверялась отдельная модель, и она была зелёной,
 * пока сам код был сломан — этот урок уже стоил одного прогона на плеере.
 *
 * ФОРМУЛА. Пара `lui rt,%hi(A)` + `lw/addiu rt,rt,%lo(A)` должна после
 * релокации дать адрес `A + S`, где `A` — адрес из файла (адденд), `S` —
 * адрес сегмента в загруженном образе. Складывается так:
 *
 *     значение  = A + S
 *     hi        = (значение + 0x8000) >> 16
 *     lo        = значение & 0xFFFF
 *
 * и тогда `hi<<16 + sext16(lo) == A + S` всегда — потому что `sext16`
 * вычитает 0x10000 ровно тогда, когда `lo >= 0x8000`, а добавленные
 * старшие полвосьмого байта (`0x8000`) как раз переносят это вычитание.
 *
 * ЗАМЕР, КОТОРЫЙ ОПРОВЕРГ ПРЕЖНЮЮ ФОРМУЛУ. Прежний вариант собирал
 * `hi` как `(hi16_адденда + S) >> 16`, то есть ОПУСКАЛ младшую половину
 * адреса. На реальном модуле (md5 27e8339e78430eaee2932806d870196b) это
 * дало 5908 неверных указателей из 24571 пары HI16/LO16 — все ровно на
 * 64 КиБ ниже намеренного адреса. Новая формула даёт 0 неверных на тех же
 * 24571 паре. Число релокаций в образе 120719 совпало с полем
 * `reloc_total` отчёта на плеере, то есть разбор образа здесь тот же,
 * что в загрузчике.
 *
 * ЧЕМ КОНЧИЛОСЬ БЕЗ ЭТОЙ ПРАВКИ. Первый конструктор `.cplinit`
 * (`0x08805024`) зовёт `0x08AD0B0C`, а там `lw a1,lo(a0)` при `a0` =
 * `0x08B60000` и `lo` = `0xB9DC` (знаковое: −0x4624) читал слово по
 * `0x08B5B9DC` — это на 64 КиБ ниже намеренного `0x08B6B9DC`. В файле по
 * смещённому адресу лежит `0xFFFFFFFF`, по намеренному — указатель
 * `0x08B6B6F0` (с `R_MIPS_32`). Гость получил `-1` и разыменовал его:
 * `lw s1,12(a1)` по адресу `0xB`. Сбой прогона на плеере, `pc=0x08AD0C14`.
 *
 * Семантика `A + S` не предположение, а общая для всех трёх типов в этом
 * загрузчике: `R_MIPS_32` прибавляет `target` к слову целиком, `R_MIPS_26`
 * прибавляет `target >> 2` к полю перехода — и именно так совпал проверенный
 * ранее якорь `0x08A9C9BC → 0x08AD75F4 (strlen)`. HI16 не может считать
 * иначе, иначе один и тот же объект получал бы два разных адреса в
 * зависимости от того, как обратился компилятор.
 */

#ifndef GUEST_RELOC_H
#define GUEST_RELOC_H

#include "guest_load.h"

/*
 * `lo_signed`  — знаковая младшая половина АДДЕНДА, то есть исходное
 *                16-битное смещение ИЗ ФАЙЛА, до правки. Берётся до
 *                применения релокаций, иначе пара читала бы уже
 *                исправленное значение.
 * `target`     — адрес сегмента в загруженном образе.
 *
 * Возвращается слово `lui` целиком, со старшими 16 битами из исходного
 * слова (opcode и регистр не меняются).
 */
static inline u32 guest_relocate_hi(u32 op, s32 lo_signed, u32 target)
{
    u32 value = (op & 0xFFFFu) << 16;

    value += (u32)lo_signed;
    value += target;
    return (op & 0xFFFF0000u) | (((value + 0x8000u) >> 16) & 0xFFFFu);
}

/* Результат пары HI16/LO16, как его увидит процессор.
 *
 * Нужен тесту, а не загрузчику: загрузчик пишет `hi` и `lo` по отдельности,
 * и согласованность двух мест проверяется только так — посчётом того, что
 * в итоге сложится регистр. */
static inline u32 guest_pair_value(u32 hi_word, u32 lo_word)
{
    s32 lo = (s32)(s16)(u16)(lo_word & 0xFFFFu);

    return (((hi_word & 0xFFFFu) << 16) + (u32)lo);
}

/* Слово LO16, которое записывает загрузчик. */
static inline u32 guest_relocate_lo(u32 op, u32 target)
{
    return (op & 0xFFFF0000u) | ((op + target) & 0xFFFFu);
}

#endif /* GUEST_RELOC_H */
