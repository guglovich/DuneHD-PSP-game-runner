/*
 * Расшифровка розничного PSP EBOOT.BIN (схема ~PSP).
 *
 * Формат и ключи — в tools/pspdecrypt, откуда взят этот модуль: инструменту
 * и рантайму нужен один и тот же код, иначе они разойдутся. Инструмент
 * pspdecrypt теперь тонкая обёртка над этим модулем.
 *
 * Ключевой факт, установленный по свежему PPSSPP: DISC_ID для расшифровки
 * НЕ НУЖЕН. Ключ выбирается по четырёхбайтовому тегу на смещении 0xD0
 * самой прошивки; для розничного EBOOT это всегда 0xC0CB167C, которому
 * соответствует ключ g_keyEBOOT2xx и код 0x5D. Схема с выводом k1 из SHA1
 * от DISC_ID — это PSP 1.00, ~2004 года, и в современных инструментах её
 * уже нет.
 *
 * Используется libkirk (PPSSPP, GPL-2.0), файлы в third_party/libkirk.
 * Лицензия LGPL/GPL на проект распространяется соответственно.
 *
 * Проверка результата: у корректно расшифрованного файла первые четыре
 * байта — магия ELF (7f 45 4c 46). Это служит и гейтом: без правильного
 * ключа результат не будет начинаться с неё.
 */

#ifndef PSP_DECRYPT_H
#define PSP_DECRYPT_H

#include <stddef.h>
#include <stdint.h>

typedef uint8_t u8;

/* Равна ли сигнатура ~PSP. Размер проверяется, чтобы не читать за конец. */
int psp_is_encrypted_eboot(const u8 *data, size_t size);

/* Расшифровка образа ~PSP.
 *
 * Возвращает новый буфер и его размер, либо NULL. При неудаче в *why
 * кладётся причина, а в *out_size — 0. Буфер освобождается через free().
 * Причину освобождать не нужно: она указывает на строку-литерал.
 */
u8 *psp_decrypt_eboot(const u8 *in, size_t size, size_t *out_size,
                      const char **why);

/* Печать заголовка ~PSP. Для инструмента, рантайму не требуется. */
void psp_decrypt_dump_header(const u8 *data, size_t size);

#endif /* PSP_DECRYPT_H */