#ifndef GE_WALK_H
#define GE_WALK_H

#include "psp_hle.h"

/* Список команд GE для ходячего.
 *
 * Чтение идёт по ВСЕМУ отображению гостя, а не по одному буферу:
 * списки GE строятся из кусков через JUMP/CALL, и прежняя модель
 * «один массив» обрывалась на первом же переходе в другой буфер
 * (измерено: список на 9382 шага остановился без единого
 * примитива).
 *
 * `mem`    — хост-указатель начала отображения гостя;
 * `base`   — runtime-адрес отображения (`0x08804000`);
 * `size`   — размер отображения (`map_size`);
 * `list_addr` — стартовый адрес, ПЕРЕДАН ГОСТЕМ (любое зеркало:
 * кэшируемое `0x08…`, безкэшевое `0x48…`, KSEG0/1). Нормализация
 * адреса делается при каждом чтении, поэтому JUMP/CALL из команд
 * могут ссылаться в любое зеркало. */
typedef struct {
    const u32 *mem;
    u32        base;
    u32        size;
    u32        list_addr;
} GeList;

/* Итог ходьбы по списку. */
typedef struct {
    u32 prim_sprites;   /* PRIM type=6 — 2D-квады */
    u32 prim_3d;        /* PRIM type=3,4,5 — 3D-геометрия */
    u32 prim_other;     /* PRIM type=0,1,2,7 */
    u32 max_vertices;   /* максимум вершин в одном PRIM */
    u32 finish;         /* число FINISH (границ кадра) */
    u32 signal;         /* число SIGNAL */
    u32 steps;          /* всего команд просмотрено */
    u32 calls;          /* макс глубина CALL */
    bool has_2d;        /* есть спрайты */
    bool has_3d;        /* есть 3D-примитивы */
} GeWalkResult;

/* Идёт по списку и классифицирует примитивы. Не эмулирует
 * растеризацию — только считывает типы. Возвращает false при
 * неверных аргументах; частичный результат всё равно пишется. */
bool ge_walk(const GeList *list, GeWalkResult *out);

#endif /* GE_WALK_H */
