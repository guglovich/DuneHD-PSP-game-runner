/*
 * Арифметика GE — порт `GPU/Software/GEMath.cpp` из PPSSPP.
 *
 * Зачем. У нас нет своего растеризатора GE: `ge_walk` только классифицирует
 * примитивы. Чтобы получить кадр, нужен растеризатор, и эталон уже написан и
 * проверен против настоящего PSP — 125 из 132 дампов кадров совпадают
 * попиксельно, включая LocoRoco.
 *
 * Здесь — скалярное ядро: формат float24, сумматор без защитных битов,
 * произведение, строка матрицы как одна сумма, обратное, обратный квадратный
 * корень и setup-обратное. Этого достаточно для трансформа вершин и градиентов
 * плоскостей, то есть для 2D-растеризатора.
 *
 * Правила переноса (важно, иначе порт молча расходится с эталоном):
 * 1. Строки матрицы — ОДНА сумма, без порядка сложения. Никаких скобок.
 * 2. Всё усечение — к нулю, не к минус бесконечности.
 * 3. Таблицы переносятся как есть: порождающих правил у них нет.
 * 4. Проверять юнит-тестом, а не глазами.
 *
 * Источник: <https://github.com/hrydgard/ppsspp/pull/22414>
 * Разбор: `docs/ppsspp-ge-reference.md`
 */

#ifndef GE_MATH_H
#define GE_MATH_H

#include <stdint.h>

typedef uint32_t u32;
typedef int32_t  s32;
typedef uint64_t u64;
typedef int64_t  s64;

/* --- float24 --------------------------------------------------------------- */

/* 32-битный float с отрезанными младшими 8 битами мантиссы: 1 знак,
 * 8 экспонента, 15 дробных. Так выглядят параметры дисплейных списков GE,
 * и в этой же точности считает большая часть конвейера. */
float ge_truncate_float24(float f);

/* Произведение двух float24, усечённое до 17 значащих бит.
 *
 * Считается в double, а не в float: усечение в float может округлить вверх
 * через границу усечения. */
float ge_product_to_float24(double d);

/* f * 2^n сложением в поле экспоненты. f обязан быть положительным. */
float ge_scale_by_pow2(float f, int n, u32 sign);

/* f * 2^e точно, пока результат остаётся нормальным. */
float ge_scale_by_pow2_exact(float f, int e);

/* --- сумматор ------------------------------------------------------------- */

/* Сложение без защитных битов: оба операнда усекаются до точности большего
 * ДО сложения, а не результат после. Поэтому прибавление малого к большому
 * теряет младшие биты малого.
 *
 * Ноль (и денормал, который GE считает нулём) оставляет второй член как есть. */
float ge_add(float a, float b);

/* То же, с усечением результата до float24. */
float ge_add_float24(float a, float b);

/* --- строка матрицы ------------------------------------------------------- */

/* Один член строки: точное произведение, усечённое до веса
 * 2^(ea + eb - 15). Хранится как мантисса и вес младшего бита. */
struct GeRowTerm {
	s32 mantissa;   /* член = mantissa * 2^lsb_exp */
	s32 lsb_exp;
};

/* Ноль и денормals дают нулевой член. */
struct GeRowTerm ge_product(float a, float b);

/* Сумма строки ОДНИМ приёмом, без порядка:
 *
 *   1. каждый член усекается до кратного наибольшему lsb среди членов;
 *   2. усечённые члены складываются точно;
 *   3. сумма усекается в float24.
 *
 * Никакая расстановка скобок не воспроизводит железо — проверено на пробах. */
float ge_row_sum(const struct GeRowTerm *terms, int count);

/* Скалярное произведение как его считает блок GE: строка без трансляции. */
float ge_dot3(float ax, float ay, float az,
              float bx, float by, float bz);

/* Нормализация: квадрат длины как скалярное произведение, затем каждая
 * компонента умножается на обратный корень от него, как float24.
 * Возвращает длину (d2 * rsqrt(d2)); нулевой вектор остаётся нулевым. */
float ge_normalize3(float *v);

/* --- обратное ------------------------------------------------------------- */

/* Сегмент таблицы обратного: b — начало сегмента в единицах 2^-17,
 * m — наклон в единицах 2^-23 на шаг. */
struct GeRecipSegment {
	s32 b;
	s32 m;
};

/* 128 сегментов. Порождающего правила нет — это хранимая таблица. */
extern const struct GeRecipSegment ge_recip_segments[128];

/* Обратное для перспективного деления, UV и освещения.
 * w обязан быть нормальным float24. */
float ge_recip(float w);

/* Обратный квадратный корень: две таблицы по 128 сегментов, отдельно для
 * чётной и нечётной экспоненты. */
extern const struct GeRecipSegment ge_rsqrt_segments[2][128];
float ge_rsqrt(float d);

/* --- setup-обратное -------------------------------------------------------- */

/* Деление на удвоенную площадь треугольника: ТРЕТЬЯ таблица, мельче —
 * 256 сегментов по старшим 16 битам мантиссы целого. */
struct GeSetupRecipSegment {
	s32 k;
	s32 m;
};

/* Имя таблицы — с суффиксом `_table`, а не `ge_setup_recip`: функция
 * `ge_setup_recip` называется так же, как в оригинале `GESetupRecip`, и без
 * суффикса они конфликтуют. В оригинале их различает регистр. */
extern const struct GeSetupRecipSegment ge_setup_recip_table[256];

/* q ~ 2^(e + 16) / absDet, e = floor(log2(absDet)). */
s64 ge_setup_recip(u64 abs_det, int *e);

/* --- прочее из документации ---------------------------------------------- */

/* Экранная координата: компонента, делённая на w, усечённая в float24,
 * затем масштаб и центр через сумматор. */
float ge_viewport(float clip_c, float clip_w, float scale, float center);

/* Экранная глубина — с округлением вниз. */
float ge_screen_z(float clip_z, float clip_w, float z_scale, float z_center);

/* Логарифм для выбора mip-уровня: экспонента и старшие 4 бита мантиссы,
 * кусочно-линейный log2, усечённый до 1/16. */
int ge_log16(float delta);

/* 15 значащих бит, усечённых: что плоскость UV оставляет от одиночного
 * значения. */
float ge_truncate_texcoord(float f);

/* u = s * R(q) хранит 24 значащих бита, усечённых: умножение float32 без
 * округления, не float24. */
float ge_uv_product(double d);

/* Освещение: Mitchell-аппроксимация над битами float. e <= 0 даёт 1. */
float ge_light_pow(float v, float e);

/* Произведение 8-битных цветов: ((2a + 1) * (2b + 1)) >> 10.
 * Одна формула для освещения и для блендинга. */
int ge_mul8(int a, int b);

/* Масштаб цвета фактором f: s = floor(256 * f), затем то же произведение.
 * Фактор 1 (s = 256) цвет не меняет. */
int ge_light_color_scale(int x, float f);

#endif /* GE_MATH_H */
