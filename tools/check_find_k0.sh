#!/bin/sh
# Самопроверка `tools/find_k0.py` на MIPS-коде с известным содержимым.
#
# Зачем. Первая версия инструмента искала записи в `$k0`/`$k1` по вхождению
# в фиксированный список опкодов и на коде гостя (2,95 МБ) выдала **ноль**.
# Ноль выглядел как результат, а означал дефект инструмента: пропущены были
# `sll rd,rs,0` (то есть `move`), `movz` и `movn` — обычные способы записи,
# а `pref` в список попадал, хотя ничего не пишет.
#
# Проверка построена на `tests/find_k0_test.c`: там перечислены 8 форм записи
# и 3 контрольные, которые писать не должны. Счёт «сколько всего» НЕ
# проверяется — он проходит и на неполном инструменте. Проверяется, что
# КАЖДАЯ форма найдена и КАЖДАЯ контрольная не дала ложного срабатывания.

set -eu

BIN="$1"

out=$(python3 tools/find_k0.py "$BIN")

n=$(printf '%s\n' "$out" | sed -n 's/^вхождений записи.*: \([0-9]*\)$/\1/p')
[ -n "$n" ] || { echo "САМОПРОВЕРКА ПРОВАЛЕНА: не разобран вывод" >&2; exit 1; }

missing=""
# 12 форм, а не 8: добавлены `mul` и `clz` (SPECIAL2, op 0x1C) и `ext`, `ins`
# (SPECIAL3, op 0x1F). Эти опкоды инструмент раньше не обрабатывал вовсе — при
# этом самопроверка проходила, то есть гейт принимал неполноту за полноту.
for m in 'addu' 'or ' 'addiu' 'lui' 'lw ' 'sll' 'movz' 'movn' \
         'mul' 'clz' 'ext' 'ins'; do
    printf '%s\n' "$out" | grep -q "$m" || missing="$missing $m"
done
if [ -n "$missing" ]; then
    echo "САМОПРОВЕРКА ПРОВАЛЕНА: не найдены формы:$missing" >&2
    printf '%s\n' "$out" >&2
    exit 1
fi

# Контрольные формы писать не должны: `sll $0` пишет в $zero, `pref` —
# подсказка, `sw` пишет в память, а не в регистр, `madd` — в hi/lo, а не в
# регистр назначения. Инструмент обязан молчать.
for m in 'rd=$0' 'pref' 'sw ' 'madd'; do
    if printf '%s\n' "$out" | grep -q "$m"; then
        echo "САМОПРОВЕРКА ПРОВАЛЕНА: ложное срабатывание на «$m»" >&2
        printf '%s\n' "$out" >&2
        exit 1
    fi
done

echo "find_k0: все 12 форм записи найдены, 4 контрольные не дали ложных ($n вхождений) — ОК"
