#!/bin/sh
# Гейт релокации HI16/LO16 — на НАСТОЯЩЕМ include/guest_reloc.h.
#
# ЗАЧЕМ ОН ОТДЕЛЬНО ОТ check-plugin ВООБЩЕ. Прежний гейт проверял, что
# указатели после релокации попадают внутрь образа. Порог слишком мягкий:
# указатель, уехавший на 64 КиБ, попадает внутрь образа ВСЁ РАВНО, и гейт
# был зелёным, пока гость на первом же конструкторе `.cplinit` читал
# слово 0xFFFFFFFF и разыменовал его. Прогон на плеере обрывался на
# pc=0x08AD0C14, и вход в гостя не достигался ни разу.
#
# Замер, ради которого написан гейт: прежняя формула смещала 5908
# указателей из 24571 пары HI16/LO16 ровно на 64 КиБ вниз. Нынешняя даёт
# 0 на тех же 24571 паре. Число релокаций в образе 120719 совпадает с
# полем reloc_total отчёта плеера.
#
# Гейт ломает ИМЕННО настоящий заголовок: копия подменяется во временном
# каталоге, и тест собирается уже против неё. Если подмена пройдёт —
# гейт проверяет не тот код, что едет на плеер.

set -e

die() { echo "ПРОВАЛ: $1"; exit 1; }

T=tests/reloc_hi_test.c
H=include/guest_reloc.h
[ -f "$T" ] || die "нет $T"
[ -f "$H" ] || die "нет $H"

echo "=== релокация HI16/LO16: настоящий код на настоящем образе ==="

CC=${CC:-gcc}
OUT=tmp/reloc_hi_test
mkdir -p tmp

$CC -O2 -Wall -Wextra -Iinclude -o "$OUT" "$T" || die "тест не собрался"
"$OUT" || die "тест провалился на настоящем коде"

# --- три намеренно испорченные копии НАСТОЯЩЕГО заголовка ---------------
# Каждая ломает ровно одну линию формулы. Любая из них обязана провалить
# тест; если нет — гейт слеп.

mangle_header() {
	# $1 - имя, $2 - что ищем, $3 - на что меняем
	python3 -c '
import sys
name, old, new = sys.argv[1], sys.argv[2], sys.argv[3]
src = open("include/guest_reloc.h").read()
if src.count(old) != 1:
    sys.exit(80)
open("tmp/bad_reloc/guest_reloc.h", "w").write(src.replace(old, new))
' "$1" "$2" "$3" || die "подмена «$1» не применилась к $H"
}

run_broken() {
	# $1 - имя, $2 - исходная строка, $3 - подмена
	mkdir -p tmp/bad_reloc
	# Заголовок в подменённом каталоге ссылается на guest_load.h —
	# он берётся из настоящего include/, иначе не соберётся вовсе.
	rm -f tmp/bad_reloc/guest_reloc.h
	mangle_header "$1" "$2" "$3"
	# ВНИМАНИЕ: пробел после -I ОБЯЗАТЕЛЕН. Написанное `-Itemp/bad_reloc`
	# разбирается как каталог `temp/bad_reloc` (без «м»), которого нет, и
	# подмена МОЛЧА не применяется — тест собирается против настоящего
	# заголовка и зелёный. Это уже случилось один раз, и гейт это поймал:
	# испорченная копия «прошла». Пробелы и выверенный путь обязательны.
	$CC -O2 -Wall -Wextra -I tmp/bad_reloc -I include \
	    -o "$OUT.broken" "$T" 2>/dev/null || die "испорченная копия «$1» не собралась"
	if "$OUT.broken" >/dev/null 2>&1; then
		die "испорченная копия «$1» ПРОЙДЕНА — гейт слеп к формеHI16"
	fi
}

# 1. Прежняя формула: из результата вычитается младшая половина адреса.
run_broken "прежняя формула (вычитание lo_signed)" \
'    return (op & 0xFFFF0000u) | (((value + 0x8000u) >> 16) & 0xFFFFu);' \
'    value -= (u32)lo_signed;
    return (op & 0xFFFF0000u) | ((value >> 16) & 0xFFFFu);'

# 2. Без переноса 0x8000: знаковое расширение lo перестаёт компенсироваться.
run_broken "без переноса +0x8000" \
'    return (op & 0xFFFF0000u) | (((value + 0x8000u) >> 16) & 0xFFFFu);' \
'    return (op & 0xFFFF0000u) | ((value >> 16) & 0xFFFFu);'

# 3. Младшая половина адреса вовсе опущена.
run_broken "младшая половина адреса опущена" \
'    value += (u32)lo_signed;
    value += target;' \
'    value += target;'

echo "=== гейт пройден (3 испорченные копии отвергнуты) ==="
