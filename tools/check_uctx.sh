#!/bin/sh
# Гейт раскладки кадра сигнала (`UCONTEXT_GREG` в src/plugin/guest_run.c).
#
# Зачем он: константа смещения была написана как `36 + 8*n` вместо `40 + 8*n` —
# на 4 байта назад для всех регистров. Число правдоподобно, комментарий рядом
# утверждал, что согласованность «проверена по шести регистрам», и ошибка молча
# портила результат: по смещению на 4 байта назад от `$sp` лежит вторая
# половина слота `$gp`, где по построению нули, поэтому `$sp` читался как 0
# при настоящем `0x2CADFD80`, и ни один кандидат не мог совпасть с `si_addr`.
# Отчёт при этом выглядел исправным.
#
# Проверяется текст объявления, а не соседний комментарий: гейт, который
# смотрит на prose, способен пройти на испорченном коде.

SRC="${1:-src/plugin/guest_run.c}"
rc=0

echo "=== UCONTEXT_GREG ==="

line=$(grep -m1 '#define[[:space:]][[:space:]]*UCONTEXT_GREG' "$SRC" 2>/dev/null)
if [ -z "$line" ]; then
	echo "ОТКАЗ: в $SRC нет определения UCONTEXT_GREG"
	exit 1
fi
echo "  объявление: $line"

const=$(printf '%s\n' "$line" \
	| grep -oE '\([[:space:]]*(0x[0-9A-Fa-f]+|[0-9]+)[[:space:]]*\+' \
	| grep -oE '(0x[0-9A-Fa-f]+|[0-9]+)')
if [ -z "$const" ]; then
	echo "ОТКАЗ: не удалось выделить константу смещения"
	exit 1
fi

if ! printf '%s\n' "$line" | grep -qE '\+[[:space:]]*8[[:space:]]*\*[[:space:]]*\(?[[:space:]]*\(?n'; then
	echo "ОТКАЗ: шаг объявления не равен 8*n"
	rc=1
else
	echo "  шаг 8*n: верно"
fi

if [ "$const" != "40" ]; then
	echo "ОТКАЗ: смещение = $const + 8*n, измерено 40 + 8*n"
	rc=1
else
	echo "  константа 40: верно"
fi

# Сверка с независимо измеренными значениями (проба tests/uctx_layout.c).
# Перечислены все семь, для которых измерение есть, а не только удобные.
for pair in 2:56:v0 4:72:a0 25:240:t9 28:264:gp 29:272:sp 30:280:fp 31:288:ra; do
	n=${pair%%:*}
	rest=${pair#*:}
	want=${rest%%:*}
	name=${rest#*:}
	got=$((const + 8 * n))
	if [ "$got" != "$want" ]; then
		echo "ОТКАЗ: \$$name (N=$n) -> $got, измерено $want"
		rc=1
	else
		echo "  \$$name (N=$n) = $got  верно"
	fi
done

if [ "$rc" -eq 0 ]; then
	echo "=== гейт пройден ==="
fi
exit $rc
