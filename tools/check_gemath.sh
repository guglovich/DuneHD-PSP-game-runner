#!/bin/sh
# Гейт таблиц арифметики GE.
#
# ЗНАЧЕНИЯ таблиц здесь НЕ проверяются, и это не упущение: они проверяются
# дифференциальным тестом `tests/ge_math_test.c`, который прогоняет GERecip,
# GERsqrt и GESetupRecip на 2,6 миллиона случайных входов и сравнивает с
# оригиналом из PPSSPP побитово. Любая неверная запись таблицы дала бы
# расхождение — проверка строго сильнее, чем сверка 640 чисел по одному.
#
# Первая версия этого гейта сверяла значения и разбирала текст таблиц
# скриптом. Она не прошла на верном коде: шаблоны не учитывали отступы, а
# регулярка в awk была не закрыта. Гейт, который не проходит на исправном коде,
# хуже отсутствующего — его начинают обходить.
#
# Здесь проверяется то, что реально может сломаться при правке и что не
# проверяет дифференциальный тест: ЧИСЛО записей в таблицах. Делается это на
# этапе компиляции через отрицательный размер массива — ошибка компиляции,
# а не рантайм-проверка, поэтому её нельзя пропустить молча.

SRC="${1:-src/ge_math.c}"
GCC="${2:-cc}"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

echo "=== размеры таблиц GE ==="

# Проверка собирается вместе с нашим файлом: если число записей в таблице
# отличается от ожидаемого, компилятор отвергнет отрицательный размер массива.
cat > "$TMP.c" <<'EOF'
#include "ge_math.h"

/* Отрицательный размер массива — ошибка компиляции, если условие неверно.
 * Именно это нужно: проверка на этапе сборки, а не в рантайме. */
typedef char check_recip[
	(sizeof(ge_recip_segments) / sizeof(ge_recip_segments[0])) == 128
	? 1 : -1];
typedef char check_rsqrt[
	(sizeof(ge_rsqrt_segments) / sizeof(ge_rsqrt_segments[0])) == 2
	? 1 : -1];
typedef char check_rsqrt_inner[
	(sizeof(ge_rsqrt_segments[0]) / sizeof(ge_rsqrt_segments[0][0])) == 128
	? 1 : -1];
typedef char check_setup[
	(sizeof(ge_setup_recip_table) / sizeof(ge_setup_recip_table[0])) == 256
	? 1 : -1];

int main(void) { return 0; }
EOF

if ! "$GCC" -Iinclude -c "$TMP.c" -o "$TMP.o" 2>"$TMP.err"; then
	echo "ОТКАЗ: размеры таблиц не совпадают с ожидаемыми"
	sed 's/^/       /' "$TMP.err" | head -8
	exit 1
fi

echo "  ge_recip_segments[128]        верно"
echo "  ge_rsqrt_segments[2][128]     верно"
echo "  ge_setup_recip_table[256]     верно"

# Значения — дифференциальным тестом. Запускаем его здесь же, чтобы гейт был
# одной командой: отдельный запуск легко забыть, а таблицы без него не
# проверяются вовсе.
#
# Собираем тест САМИ, а не берём готовый `tmp/ge_math_test`: иначе гейт
# проверяет прежнюю сборку. Именно это и произошло — после восстановления
# исходника гейт гонял собранный ранее испорченный бинарник и показывал
# расхождения на уже исправленном коде.
if ! "$GCC" -O2 -Iinclude -Itests tests/ge_math_test.c src/ge_math.c \
          -o tmp/ge_math_test -lm 2>"$TMP.err"; then
	echo "ОТКАЗ: не удалось собрать дифференциальный тест"
	sed 's/^/       /' "$TMP.err" | head -8
	exit 1
fi

if [ -x tmp/ge_math_test ]; then
	echo "--- дифференциальный тест ---"
	if ./tmp/ge_math_test > "$TMP.out" 2>&1; then
		tail -2 "$TMP.out" | sed 's/^/  /'
	else
		echo "ОТКАЗ: дифференциальный тест не пройден"
		tail -12 "$TMP.out" | sed 's/^/       /'
		exit 1
	fi
else
	echo "  дифференциальный тест не собран — соберите: make ge-math-test"
	echo "  (без него значения таблиц не проверяются)"
	exit 1
fi

echo "=== гейт пройден ==="
exit 0
