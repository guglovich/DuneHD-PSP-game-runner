#!/bin/sh
# Гейт на байты трамплина импорта.
#
# Зачем. Трамплин — это код, пишущийся в отображение гостя. Проверить его
# исполнением на хосте нельзя, а на плеере он падает как SIGILL, и локализовать
# падение нечем: поле адреса инструкции в ucontext достоверно только для
# SIGTRAP (см. docs/guest-entry.md). Единственный оставшийся инструмент —
# собрать те же байты здесь и прочитать их дизасмом.
#
# Что проверяется:
#   * ровно 37 слов трамплина, и все они декодируются как инструкции;
#   * ни одно слово не осталось неопознанным (это и был признак «сюда попали
#     данные, а не код»);
#   * стаб — это `j` плюс `nop`, ровно два слова: слот стаба импорта шириной
#     8 байт, и лишнее слово затерло бы начало соседнего импорта;
#   * стаб прыгает в трамплин, а не куда попало.
#
# Гейт построен на СВЕРКЕ ПОСЛЕДОВАТЕЛЬНОСТИ, а не на подсчёте инструкций.
# Причина: objdump на MIPS не отличает код от данных — он декодирует почти
# любое слово как корректную инструкцию. Проверено на этот гейт: и `sw ra,0($zero)`
# (знаменитый старый баг с незаполненным rs), и ASCII `i_ad` проходят проверку
# «все слова декодируются» без единого возражения. Такая проверка принципиально
# не работает, и гейт на ней был бы зелёным ровно на свой собственный дефект.
#
# Работающий способ — сверить каждое слово по позиции: ожидается ровно та
# последовательность, которую собирает guest_build_import_trampoline. Любое
# смещение, подмена или попадание данных сдвигает или меняет строку, и гейт это
# видит.

set -eu

OBJDUMP="$1"
BIN="$2"

# Разбираем вывод objdump в строки вида "номер: мнемоника операнды", нормализуя
# пробелы: между полями objdump ставит табы непоследовательно, и от шаблона по
# пробелу иначе зависит версия binutils. Подстановка в `case` табы теряет,
# поэтому приводим к одному виду заранее.
out=$("$OBJDUMP" -D -b binary -m mips:isa32 -EL "$BIN" | \
        sed -n 's/^[[:space:]]*\([0-9a-f]\{1,8\}\):[[:space:]]*[0-9a-f]\{8\}[[:space:]]\+//p' | \
        tr -s ' \t' ' ' | tr -d '\r')

# Ожидаемая последовательность. Порядок и содержание — как в
# guest_build_import_trampoline; любая правка там обязана идти и сюда.
expected='j 0x8ca3500
nop
addiu sp,sp,-64
sw ra,0(sp)
sw a0,8(sp)
sw a1,12(sp)
sw a2,16(sp)
sw a3,20(sp)
lw t0,80(sp)
sw t0,24(sp)
lw t1,84(sp)
sw t1,28(sp)
lw t2,88(sp)
sw t2,32(sp)
sw t8,40(sp)
sw t9,44(sp)
sw k0,48(sp)
sw k1,52(sp)
lui t9,0x2aab
addiu t9,t9,-19516
lui t8,0x2aad
addiu t8,t8,16
move gp,t8
li a0,0
addiu a1,sp,8
move a2,k0
move a3,ra
jalr t9
nop
lw ra,0(sp)
lw a0,8(sp)
lw a1,12(sp)
lw a2,16(sp)
lw a3,20(sp)
lw t8,40(sp)
lw t9,44(sp)
lui k0,0x8bd
addiu k0,k0,-16684
lw k1,52(sp)
addiu sp,sp,64
lui t0,0x2aaa
ori t0,t0,0xb3c4
move t1,k0
sw t1,0(t0)
jr ra
nop'

tmp_exp=$(mktemp)
tmp_got=$(mktemp)
trap 'rm -f "$tmp_exp" "$tmp_got"' EXIT
printf '%s\n' "$expected" > "$tmp_exp"
printf '%s\n' "$out" > "$tmp_got"

if ! cmp -s "$tmp_exp" "$tmp_got"; then
    echo "ГЕЙТ ПРОВАЛЕН: байты трамплина не совпадают с ожидаемыми." >&2
    echo "--- ожидалось | получено ---" >&2
    diff "$tmp_exp" "$tmp_got" >&2 || true
    exit 1
fi

echo "трамплин: 44 слова совпали (плюс стаб из 2 слов) с ожидаемой последовательностью, стаб 8 байт — ОК"

# Отдельно — смысловая проверка, которой нет в сверке строк: пара `lui`/`addiu`
# обязана складываться в РОВНО переданный адрес.
#
# Соблазнительно проверять это как «hi = (v+0x8000)>>16, lo = v & 0xFFFF», но
# такая проверка зелёная и на `ori`: у `ori` нет знакового расширения, и при
# `lo >= 0x8000` адрес собирается на `0x10000` выше. Именно это стоило SIGILL
# на плеере — вызов уходил в `.rodata`. Поэтому проверка пересобирает адрес
# так, как это делает процессор, а не как предполагает формула.
#
# HOST_FN и HOST_GP — те же значения, что в tests/tramp_dump.c.
# Значения взяты из tests/tramp_dump.c и ОБЯЗАТЕЛЬНО имеют младшие биты
# `>= 0x8000`.
#
# Это не случайно. При `lo < 0x8000` `ori` и `addiu` дают ОДИНАКОВЫЙ адрес, и
# проверка была бы зелёной на той самой ошибке, ради которой написана. Проверено
# на её первой версии: с `lo = 0x3314` подмена `ori` на `addiu` не дала ни
# одного возражения. Реальные адреса на плеере были другими —
# `fn = 0x2AAAB3C4` (`lo = 0xB3C4`) и `gp = 0x2AAD0010`, — и там разница
# составляла ровно `0x10000`.
HOST_FN=0x2AAAB3C4
HOST_GP=0x2AAD0010
HOST_K0=0x08BCBED4

rebuilt() {
    # $1 = hi, $2 = lo, $3 = множитель опкода (0 = addiu, 1 = ori)
    hi=$1; lo=$2; kind=$3
    base=$(( hi << 16 ))
    if [ "$kind" -eq 0 ]; then
        if [ "$lo" -ge 32768 ]; then
            base=$(( base + lo - 65536 ))
        else
            base=$(( base + lo ))
        fi
    else
        base=$(( base | lo ))
    fi
    printf '0x%08X' "$base"
}

# Строки сложения половин находятся ПО СОДЕРЖИМОМУ, а не по номеру строки.
# Номер был зашит жёстко и разошёлся с выводом objdump ровно на два, причём
# проверка об этом сообщала невнятно («16#lui») — то есть указывала не на
# расхождение номеров, а на последствие. Поиск по `lui t9`/`lui t8` устойчив к
# любой правке в трамплине.
fn_line=$(printf '%s\n' "$out" | grep -m1 '^lui t9,')
gp_line=$(printf '%s\n' "$out" | grep -m1 '^lui t8,')
[ -n "$fn_line" ] && [ -n "$gp_line" ] || {
    echo "ГЕЙТ ПРОВАЛЕН: в трамплине нет lui t9 или lui t8" >&2
    exit 1
}

# Строка СРАЗУ ПОСЛЕ `lui` несёт младшую половину. Берётся по соседству, а не
# по номеру: objdump печатает `addiu` непосредственный операнд ДЕСЯТИЧНЫМ, так
# что искать его как `0x...` нельзя.
fn_lo_line=$(printf '%s\n' "$out" | grep -A1 -m1 '^lui t9,' | sed -n '2p')
gp_lo_line=$(printf '%s\n' "$out" | grep -A1 -m1 '^lui t8,' | sed -n '2p')
[ -n "$fn_lo_line" ] && [ -n "$gp_lo_line" ] || {
    echo "ГЕЙТ ПРОВАЛЕН: нет строки сразу после lui" >&2
    exit 1
}
fn_hi=$(printf '%s' "$fn_line" | grep -oE '0x[0-9a-fA-F]+$')
gp_hi=$(printf '%s' "$gp_line" | grep -oE '0x[0-9a-fA-F]+$')
# Младшая половина у `addiu` десятичная (со знаком), у `ori` — шестнадцатеричная.
fn_lo=$(printf '%s' "$fn_lo_line" | sed 's/.*,//')
gp_lo=$(printf '%s' "$gp_lo_line" | sed 's/.*,//')

fn_kind=0
gp_kind=0
case "$fn_lo_line" in *addiu*) fn_kind=0 ;; *ori*) fn_kind=1 ;; esac
case "$gp_lo_line" in *addiu*) gp_kind=0 ;; *ori*) gp_kind=1 ;; esac

# Третья пара — адрес `SceThreadContext`, который трамплин УСТАНАВЛИВАЕТ в `$k0`.
# Проверяется тем же способом: пара обязана складываться ровно в переданный
# адрес, и `addiu` обязан быть именно `addiu` — при `lo >= 0x8000` подмена на
# `ori` уводит адрес на `0x10000`, и гость падает на вызове.
k0_line=$(printf '%s\n' "$out" | grep -m1 '^lui k0,')
[ -n "$k0_line" ] || {
    echo "ГЕЙТ ПРОВАЛЕН: в трамплине нет lui k0 — \$k0 не устанавливается" >&2
    exit 1
}
k0_lo_line=$(printf '%s\n' "$out" | grep -A1 -m1 '^lui k0,' | sed -n '2p')
[ -n "$k0_lo_line" ] || {
    echo "ГЕЙТ ПРОВАЛЕН: нет строки сразу после lui k0" >&2
    exit 1
}
k0_hi=$(printf '%s' "$k0_line" | grep -oE '0x[0-9a-fA-F]+$')
k0_lo=$(printf '%s' "$k0_lo_line" | sed 's/.*,//')
k0_kind=0
case "$k0_lo_line" in *addiu*) k0_kind=0 ;; *ori*) k0_kind=1 ;; esac
case "$k0_lo" in
0x*) k0_lo=$((k0_lo)) ;;
*)  k0_lo=$(( k0_lo & 0xFFFF )) ;;
esac
k0_got=$(rebuilt "$((k0_hi))" "$((k0_lo))" "$k0_kind")

# Знаковый операнд `addiu` приводится к маске, а не используется как есть:
# `rebuilt` ждёт 0..0xFFFF и сам разбирается со знаком.
case "$fn_lo" in
0x*) fn_lo=$((fn_lo)) ;;
*)  fn_lo=$(( fn_lo & 0xFFFF )) ;;
esac
case "$gp_lo" in
0x*) gp_lo=$((gp_lo)) ;;
*)  gp_lo=$(( gp_lo & 0xFFFF )) ;;
esac

fn_got=$(rebuilt "$((fn_hi))" "$((fn_lo))" "$fn_kind")
gp_got=$(rebuilt "$((gp_hi))" "$((gp_lo))" "$gp_kind")

fn_want=$(printf '0x%08X' "$HOST_FN")
gp_want=$(printf '0x%08X' "$HOST_GP")

[ "$fn_got" = "$fn_want" ] || {
    echo "ГЕЙТ ПРОВАЛЕН: трамплин зовёт $fn_got, а hle_import по $fn_want" >&2
    exit 1
}
[ "$gp_got" = "$gp_want" ] || {
    echo "ГЕЙТ ПРОВАЛЕН: трамплин ставит \$gp = $gp_got, а нужно $gp_want" >&2
    exit 1
}
k0_want=$(printf '0x%08X' "$HOST_K0")
[ "$k0_got" = "$k0_want" ] || {
    echo "ГЕЙТ ПРОВАЛЕН: трамплин ставит \$k0 = $k0_got, а нужно $k0_want" >&2
    exit 1
}

echo "адрес функции, \$gp и \$k0 собираются точно ($fn_got, $gp_got, $k0_got) — ОК"
