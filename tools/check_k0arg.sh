#!/bin/sh
# Гейт смещений ПЯТОГО и ШЕСТОГО аргументов в `guest_thread_enter`.
#
# ЗА ЧЕМ ОН. `guest_thread_enter` — сырая ассемблерная функция БЕЗ пролога,
# читающая два аргумента из кадра вызывающего. Смещения обязаны СОВПАДАТЬ со
# смещениями записи у вызывающего.
#
# ПРЕДЫДУЩАЯ ВЕРСИЯ ГЕЙТА УТВЕРЖДАЛА, что смещение больше на 8, и это было
# неверно. Ошибка перешла из модели «`jalr` кладёт адрес возврата на стек»,
# а на MIPS o32 `jalr` этого НЕ делает: адрес возврата уходит в `$ra`, `$sp`
# не меняется, и пятый аргумент лежит по `sp+16` у обеих сторон.
#
# Чем кончилось: `lw $11,24($sp)` читал не пятый аргумент, а `sw gp,24(sp)`
# в кадре `guest_thread` — то есть `$gp`. Значение правдоподобное (указатель
# наш, не ноль), поэтому правка выглядела как исправление, а была заменой
# одного мусора другим. Гейт того времени проверял согласованность двух
# неверных сторон и потому был зелёным.
#
# ЗАМЕР, КОТОРЫЙ ОПРОВЕРГ МОДЕЛЬ (живой плеер, главный поток):
#   `lw $11,24($sp)` вернул `2D0EC010` — байт в байт то, что `guest_thread`
#   положил в свой кадр по `24(sp)` инструкцией `sw gp,24(sp)`, а `$gp` в том
#   же кадре дампа равен `2D0EC010`.
#   Пятый аргумент там же лежит по `16(sp)` и равен нулю — и `lw $11,24($sp)`
#   нуля не вернул.
#   Вывод: `$sp` у вызывающего и callee ОДИН И ТОТ ЖЕ.
#
# Проверяется ДИЗАСМ СОБРАННОЙ БИБЛИОТЕКИ, а не исходник: смещение в исходнике
# верное, а ошибку вносит компилятор или правка вызывающей стороны.
# Сверяются ВСЕ вызывающие стороны, а не одна: `guest_thread` и `worker_thread`
# компилируются по-разному (разные размеры кадра), и проверка только первой
# пропустила бы расхождение во второй.
#
# ПРИЗНАК ПОИСКА УСТОЙЧИВ К ПЕРЕСТАНОВКЕ ИНСТРУКЦИЙ. Раньше сторона вызывающего
# искалась как «первая запись `sw …(sp)` сразу после загрузки `$t9` из GOT» —
# это рассыпалось, когда компилятор поставил между ними `move a3,zero`.
# Теперь берётся окно вокруг `jalr` (24 строки назад, ОДНА строка вперёд:
# часть стековых аргументов компилятор кладёт в слот задержки).
#
# Гейт обязан падать на испорченной копии; проверяется отдельно.

SO="${1:-native_code.so}"
OBJ="${2:-/home/jinseoyeon/Projects/Dune Max/toolchain/bootlin-mips32el-musl/bin/mipsel-buildroot-linux-musl-objdump}"
rc=0

if [ ! -f "$SO" ]; then
	echo "=== guest_thread_enter: стековые аргументы ==="
	echo "ОТКАЗ: нет $SO"
	exit 1
fi

asm=$("$OBJ" -d --section=.text "$SO" 2>/dev/null)

# Что читает callee.
read_offs=$(printf '%s\n' "$asm" \
	| awk '/<guest_thread_enter>:/{f=1} f&&/^$/{exit} f' \
	| grep -oE 'lw[[:space:]]+t[34],[0-9]+\(sp\)' \
	| grep -oE '[0-9]+\(sp\)' | tr -d '(sp)' | sort -n | tr '\n' ' ')

# Что кладёт каждый вызывающий: окно стековых слотов вокруг `jalr`.
caller_offs() {
	printf '%s\n' "$asm" \
	| awk -v fn="<$1>:" '$0 ~ fn{f=1} f&&/^$/{exit} f' \
	| awk '/jalr[ \t]+t9/{n=NR} {ln[NR]=$0} END{
	        if (!n) exit 1
	        for (i = (n > 24 ? n - 24 : 1); i <= n + 1; i++) {
	            if (match(ln[i], /sw[ \t]+[a-z0-9]+,[0-9]+\(sp\)/)) {
	                s = substr(ln[i], RSTART, RLENGTH)
	                sub(/.*,/, "", s)
	                sub(/\(sp\).*/, "", s)
	                if (s + 0 >= 16) print s
	            }
	        }
	    }' | sort -n | uniq | tr '\n' ' '
}

echo "=== guest_thread_enter: стековые аргументы ==="
echo "  callee читает по          : ${read_offs:-НЕ НАЙДЕНО}(sp)"
for fn in guest_thread worker_thread; do
	echo "  $fn кладёт по : $(caller_offs "$fn" || echo НЕ НАЙДЕНО)(sp)"
done

if [ -z "$read_offs" ]; then
	echo "ОТКАЗ: не удалось разобрать callee — гейт ничего не проверил"
	exit 1
fi

has() {
	for w in $1; do
		[ "$w" = "$2" ] && return 0
	done
	return 1
}

for fn in guest_thread worker_thread; do
	store=$(caller_offs "$fn")
	if [ -z "$store" ]; then
		echo "ОТКАЗ: $fn не найден или не найден его вызов — гейт ничего не проверил"
		rc=1
		continue
	fi
	# Пятый аргумент: 16, шестой: 20 — и СОВПАДЕНИЕ, без сдвига.
	if has "$store" 16 && has "$read_offs" 16; then
		echo "  $fn: 5-й аргумент 16(sp) -> 16(sp), сдвига нет: OK"
	else
		echo "ОТКАЗ: $fn, 5-й аргумент: нет пары 16(sp) -> 16(sp)"
		echo "       (вызывающий: ${store}; callee: ${read_offs})"
		rc=1
	fi
	if has "$store" 20 && has "$read_offs" 20; then
		echo "  $fn: 6-й аргумент 20(sp) -> 20(sp), сдвига нет: OK"
	else
		echo "ОТКАЗ: $fn, 6-й аргумент: нет пары 20(sp) -> 20(sp)"
		echo "       (вызывающий: ${store}; callee: ${read_offs})"
		rc=1
	fi
done

# Контрольное значение. Прежний гейт требовал 24/28 — именно то неверное
# смещение, из-за которого `$k0` получал `$gp` вызывающего. Его возврат
# означал бы, что гейт снова проверяет старую неверную модель.
if has "$read_offs" 24 || has "$read_offs" 28; then
	echo "ОТКАЗ: callee читает 24(sp)/28(sp) — это сдвиг 8 от модели о32, в которой"
	echo "       jalr кладёт адрес возврата на стек. На MIPS он этого не делает."
	rc=1
fi

if [ "$rc" -eq 0 ]; then
	echo "=== гейт пройден ==="
fi
exit $rc