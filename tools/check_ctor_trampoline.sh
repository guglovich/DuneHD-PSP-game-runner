#!/bin/sh
# Гейт трамплина вызова конструктора `guest_call_ctor`.
#
# ЗАЧЕМ. Конструктор возвращается `jr $ra`. Адрес возврата записывает
# только `jalr`, поэтому прыжок к конструктору обязан быть `jalr $25`.
# При `jr $25` `$ra` оставался от `guest_thread`, и конструктор
# возвращался МИМО блока восстановления `$s0–$s8`, `$gp`, `$ra` и `$sp`.
# Блок восстановления становился мёртвым кодом: ни один переход во всём
# модуле на него не вёл (проверено отдельно, до написания гейта).
# Следствие — после КАЖДОГО конструктора `$sp` висел на 48 байт ниже, и
# `lw $gp,24($sp)` в `guest_thread` читал чужой слот.
#
# ЗАМЕР, КОТОРЫЙ К ЭТОМУ ПРИВЁЛ. На плеере `$gp` равнялся `$s6` и был
# равен адресу `early_log` вместо `_gp`. `$s6` — ровно то, что лежит в
# слоте 24 кадра `guest_call_ctor` (инструкция `sw $22,24($sp)`), то есть
# наблюдение объясняется НАВЕРНЯКА только недостающими 48 байтами.
# Сама `$s6` собирается как `%got(early_log) + 0x37BC`, что и даёт её
# значение `base + 0x37BC`.
#
# Почему гейт разбирает СОБРАННУЮ библиотеку, а не исходник. В комментариях
# `guest_run.c` старая форма `jr $25` процитирована — для объяснения, чем
# она была плоха. Текстовый поиск по `.c` сматчил бы собственную цитату и
# дал ложное срабатывание. Это тот же урок, что уже поймал гейт
# `check_faultfilter`, где пришлось отфильтровывать строки-комментарии.
# Библиотека комментариев не содержит вовсе, поэтому проверка по ней честна
# по построению.
#
# Гейт ОБЯЗАН проваливаться на НАМЕРЕННО ИСПОРЧЕННОЙ КОПИИ СОБРАННОЙ
# библиотеки: одно слово `jalr` подменяется на `jr` прямо в копии `.so`.
# Если такая копия пройдёт — гейт проверяет не то, ради чего написан.

set -e

die() { echo "ПРОВАЛ: $1"; exit 1; }

SO=native_code.so
[ -f "$SO" ] || die "нет $SO"

# Путь содержит пробел («Dune Max»), поэтому и значение, и вызов обязаны
# быть в кавычках — без них sh режет команду по пробелу и гейт падает
# с вводящим в заблуждение «нет такого файла».
TC=${TC:-"../Dune Max/toolchain/bootlin-mips32el-musl"}
OBJDUMP=${OBJDUMP:-"$TC/bin/mipsel-buildroot-linux-musl-objdump"}

mkdir -p tmp

echo "=== трамплин конструктора: настоящая собранная библиотека ==="

"$OBJDUMP" -d --disassemble=guest_call_ctor "$SO" > tmp/ctor_tramp.dis ||
	die "не удалось разобрать guest_call_ctor из $SO"

# Разбор и проверка — отдельной программой, чтобы её же запустить и на
# испорченной копии. Возвращает 0 — годно, 1 — провал, 80/81 — сама
# сломалась (нет функции, нет инструкции).
check() {
	python3 tools/_ctor_trampoline_check.py "$1"
}

check tmp/ctor_tramp.dis || die "настоящая библиотека не прошла проверку трамплина"

# --- намеренно испорченная копия СОБРАННОЙ библиотеки --------------------
# Меняем ровно одно слово в `.text`: `jalr` на `jr` того же регистра.
# Остальное — как на плеере, байт в байт.
BROKEN=tmp/native_code_ctor_broken.so
cp "$SO" "$BROKEN"

python3 - "$SO" "$BROKEN" <<'PY' || die "не удалось подменить jalr на jr"
import re, sys

src, dst = sys.argv[1], sys.argv[2]

jalr = None
for line in open("tmp/ctor_tramp.dis"):
    m = re.match(r'\s+([0-9a-f]+):\s+([0-9a-f]{8})\s+jalr\b', line)
    if m:
        jalr = (int(m.group(1), 16), int(m.group(2), 16))
        break
if jalr is None:
    sys.exit(80)

addr, word = jalr
# `jr` отличается от `jalr` только полем rd (0 против 31) и funct (8 против 9).
jr = (word & 0x03E00000) | 0x00000008

data = bytearray(open(src, "rb").read())
off = addr  # сегмент .text лежит по смещению 0, так что файловый сдвиг == vaddr
if data[off:off+4] != word.to_bytes(4, "little"):
    sys.exit(81)
data[off:off+4] = jr.to_bytes(4, "little")
open(dst, "wb").write(data)
print("подмена: адрес 0x%06x, слово 0x%08x -> 0x%08x" % (addr, word, jr))
PY

"$OBJDUMP" -d --disassemble=guest_call_ctor "$BROKEN" > tmp/ctor_tramp_broken.dis ||
	die "испорченная копия не разобралась"

if check tmp/ctor_tramp_broken.dis; then
	die "испорченная копия ПРОЙДЕНА — гейт слеп и проверяет не то"
fi
echo "испорченная копия отвергнута — гейт работает"

echo "=== гейт трамплина пройден ==="
