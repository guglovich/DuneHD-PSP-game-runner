float ge_recip(float w)
{
	u32 bits = fbits(w);
	u32 i = (bits >> 8) & 0x7FFFu;
	int e = (int)((bits >> 23) & 0xFFu) - 127;
	const struct GeRecipSegment *seg = &ge_recip_segments[i >> 8];
	s32 q = (64 * seg->b + 63 + seg->m * (s32)(i & 255u)) >> 7;
	u32 signbit = bits & 0x80000000u;

	/* Результат может быть денормалом (q не больше 2^16). */
	if (e >= 126) {
		/* ldexpf(q, -16 - e) без libm: считаем степень двойки целиком. */
		float v = (float)q;
		int n = -16 - e;
		int step = (n >= 0) ? 1 : -1;
		int left = (n >= 0) ? n : -n;

		while (left-- > 0)
			v = (step > 0) ? v * 2.0f : v * 0.5f;
		return bitsf(fbits(v) | signbit);
	}
	/* Только знаковый бит, а НЕ все биты w: иначе в результат попадают
	 * экспонента и мантисса исходного числа. Именно это давало расхождение
	 * во всех 200000 проверках GERecip. */
	return ge_scale_by_pow2((float)q, -16 - e, signbit);
}

