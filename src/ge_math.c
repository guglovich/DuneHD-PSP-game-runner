/* Старший бит мантиссы целого: через подсчёт ведущих нулей, без цикла.
 *
 * `__builtin_clz` при -fno-builtin остаётся встроенной инструкцией MIPS
 * `clz`, и это не вызов libm. */
static int ge_unsigned_log2(u32 v)
{
	if (v == 0)
		return 0;
	return 31 - __builtin_clz(v);
}

s64 ge_setup_recip(u64 abs_det, int *e)
{
	u32 hi = (u32)(abs_det >> 32);
	u32 lo = (u32)abs_det;
	/* Для старшей половины сдвиг на 32 обязателен: `ex` — это логарифм ВСЕГО
	 * 64-битного числа, а не его старших 32 бит. В оригинале это
	 * `63 - clz32(hi)`, что равно `32 + log2(hi)`. Без сдвига индекс выходил
	 * на 16776960 вместо диапазона [0, 65536), и таблица читалась за границей. */
	int ex = hi ? ge_unsigned_log2(hi) + 32 : ge_unsigned_log2(lo);
	u32 index;

	*e = ex;
	/* index = (absDet << 16) >> ex - 65536: 16-битный индекс сегмента.
	 * Сдвиг на ex не может превысить 63, потому что ex = floor(log2).
	 *
	 * Ограничение: `abs_det << 16` обязан помещаться в 64 бита, то есть
	 * abs_det < 2^48. Иначе старшие биты отбрасываются, индекс выходит
	 * отрицательным и таблица читается за границей. В оригинале это
	 * недостижимо — absDet есть удвоенная площадь треугольника в фиксированной
	 * точке 12.4 (не больше ~2^31), — но проверять это надо, и тест такое
	 * переполнение уже ловил. */
	index = (u32)((abs_det << 16) >> ex) - 65536u;
	{
		const struct GeSetupRecipSegment *seg =
			&ge_setup_recip_table[index >> 8];
		return (s64)(2 * (s64)seg->k + seg->m * (s32)(index & 255u)) >> 8;
	}
}

/* --- экранные координаты -------------------------------------------------- */

float ge_viewport(float clip_c, float clip_w, float scale, float center)
{
	u32 wb = fbits(clip_w);
	u32 cb = fbits(clip_c);
	int we = (int)((wb >> 23) & 0xFFu);
	int ce = (int)((cb >> 23) & 0xFFu);
	float w, ndc;

	/* Обход `fabsf`/`isfinite`: достаточно проверить поле экспоненты.
	 * Обе конечные и ненулевые — ненормальные значения отсекаются по полю. */
	if (we == 0 || we == 255 || ce == 0 || ce == 255)
		return clip_c * scale / clip_w + center;
	if (scale == 0.0f)
		return center;

	w = ge_truncate_float24(clip_w);
	ndc = ge_product_to_float24(
		(double)ge_truncate_float24(clip_c) * ge_recip(w));
	return ge_add(ge_product_to_float24((double)ndc * scale), center);
}

float ge_screen_z(float clip_z, float clip_w, float z_scale, float z_center)
{
	float v = ge_viewport(clip_z, clip_w, z_scale, z_center);
	int i = (int)v;   /* усечение к нулю */

	/* floorf без libm: корректно для |v| < 2^23, чего достаточно для
	 * экранной глубины (0..65535 до масштаба). */
	if (v < 0.0f && (float)i != v)
		i -= 1;
	return (float)i;
}

/* --- прочее --------------------------------------------------------------- */

int ge_log16(float delta)
{
	u32 u = fbits(delta);
	int useful = (int)((u >> 19) & 0x0FFFu);

	return useful - 127 * 16;
}

float ge_truncate_texcoord(float f)
{
	return bitsf(fbits(f) & 0xFFFFFE00u);
}

float ge_uv_product(double d)
{
	u64 b;

	__builtin_memcpy(&b, &d, sizeof(b));
	if (((b >> 52) & 0x7FFu) != 0x7FFu) {
		b &= ~((1ULL << (52 - 23)) - 1ULL);
	}
	__builtin_memcpy(&d, &b, sizeof(d));
	return (float)d;
}

float ge_light_pow(float v, float e)
{
	u32 ix;
	double t;

	if (e <= 0.0f)
		return 1.0f;
	if (v <= 0.0f)
		return v;

	ix = fbits(v);
	/* Порядок умножений сохранён как в оригинале: сначала e на логарифм,
	 * затем на 1/16. trunc — приведением к s64: точно для |X| < 2^63,
	 * а здесь X не больше нескольких тысяч. */
	t = (double)(s64)((double)e
	                 * (double)(s32)(ix - 0x3F800000u)
	                 * (1.0 / 16.0)) * 16.0
	  + 1065353216.0;
	if (t < 0.0)
		t = 0.0;
	if (t > 2139095039.0)
		t = 2139095039.0;
	return bitsf((u32)(s64)t);
}

int ge_mul8(int a, int b)
{
	return ((2 * a + 1) * (2 * b + 1)) >> 10;
}

int ge_light_color_scale(int x, float f)
{
	int s = (int)(256.0f * f);

	if (s < 0)
		s = 0;
	if (s > 256)
		s = 256;
	return ((x + x + 1) * (2 * s + 1)) >> 10;
}
