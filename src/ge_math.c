/*
 * Арифметика GE — скалярное ядро.
 *
 * Перенос из `GPU/Software/GEMath.cpp` PPSSPP (PR 22414). Формулы проверены
 * на настоящем PSP и описаны в `docs/ppsspp-ge-reference.md`.
 *
 * Отличие от оригинала: здесь НЕТ вызовов libm. Плагин собирается `-nostdlib`
 * и не имеет `NEEDED`, поэтому `floorf`, `fabsf`, `ldexpf` дали бы неразрешённые
 * символы, и гейт самодостаточности бы их показал. Всё, что нужно, сделано
 * целочисленными приёмами над битами float.
 */

#include "ge_math.h"

/* --- доступ к битам -------------------------------------------------------
 *
 * Через `__builtin_memcpy`, а не приведение указателя: приведение нарушает
 * strict aliasing и даёт предупреждение, а проект собирается без предупреждений.
 * Размер фиксирован, поэтому компилятор разворачивает это в одну загрузку. */
static u32 fbits(float f)
{
	u32 b;

	__builtin_memcpy(&b, &f, sizeof(b));
	return b;
}

static float bitsf(u32 b)
{
	float f;

	__builtin_memcpy(&f, &b, sizeof(f));
	return f;
}

/* --- float24 --------------------------------------------------------------- */

float ge_truncate_float24(float f)
{
	return bitsf(fbits(f) & 0xFFFFFF00u);
}

float ge_product_to_float24(double d)
{
	u64 b;

	__builtin_memcpy(&b, &d, sizeof(b));
	/* Не денормал и не бесконечность: усекаем до 17 значащих бит.
	 * Сравнение с 0x7FF — по полю экспоненты double. */
	if (((b >> 52) & 0x7FFu) != 0x7FFu) {
		b &= ~((1ULL << (52 - 15)) - 1ULL);
	}
	__builtin_memcpy(&d, &b, sizeof(d));
	return (float)d;
}

float ge_scale_by_pow2(float f, int n, u32 sign)
{
	return bitsf((u32)((s32)fbits(f) + n * (1 << 23)) | sign);
}

/* Точное умножение на степень двойки, пока результат остаётся нормальным.
 *
 * За пределами нормального диапазона идём последовательным умножением на 2
 * или 1/2. Цикл ограничен (|e| не больше 1074), и достижим только там, где
 * результат денормал или бесконечность, — для экранных координат это
 * недостижимо. */
float ge_scale_by_pow2_exact(float f, int e)
{
	u32 b = fbits(f);
	int field = (int)((b >> 23) & 0xFFu);

	if (field == 0 || field == 255 || field + e < 1 || field + e > 254)
	{
		int step = (e >= 0) ? 1 : -1;
		int left = (e >= 0) ? e : -e;

		while (left-- > 0)
			f = (step > 0) ? f * 2.0f : f * 0.5f;
		return f;
	}
	return bitsf(b + ((u32)e << 23));
}

/* --- сумматор ------------------------------------------------------------- */

float ge_add(float a, float b)
{
	u32 ba = fbits(a);
	u32 bb = fbits(b);
	int ea = (int)((ba >> 23) & 0xFFu);
	int eb = (int)((bb >> 23) & 0xFFu);
	int na, nb;

	/* Ноль (и денормал, который GE считает нулём) оставляет второй член. */
	if (ea == 0 || eb == 0) {
		if (ea == 0 && eb == 0)
			return 0.0f;
		return (ea == 0) ? ge_truncate_float24(b)
		                 : ge_truncate_float24(a);
	}

	/* Оба операнда усекаются до точности БОЛЬШЕГО до сложения.
	 * `8 + emax - e` — это отрезать 8 бит параметра плюс разницу экспонент. */
	if (ea > eb) {
		na = 8 + ea - ea;   /* = 8 */
		nb = 8 + ea - eb;
	} else {
		na = 8 + eb - ea;
		nb = 8 + eb - eb;   /* = 8 */
	}
	if (na >= 24)
		ba &= 0x80000000u;
	else
		ba &= ~((1u << na) - 1u);
	if (nb >= 24)
		bb &= 0x80000000u;
	else
		bb &= ~((1u << nb) - 1u);
	return bitsf(ba) + bitsf(bb);
}

float ge_add_float24(float a, float b)
{
	return ge_truncate_float24(ge_add(a, b));
}

/* --- строка матрицы ------------------------------------------------------- */

struct GeRowTerm ge_product(float a, float b)
{
	u32 ba = fbits(a);
	u32 bb = fbits(b);
	int ea = (int)((ba >> 23) & 0xFFu);
	int eb = (int)((bb >> 23) & 0xFFu);
	u64 ma, mb;
	s32 m;
	struct GeRowTerm t;

	if (ea == 0 || eb == 0) {
		t.mantissa = 0;
		t.lsb_exp = -100000;   /* ниже любого настоящего lsb */
		return t;
	}

	/* Мантиссы по 24 бита дают произведение с 46 дробными битами,
	 * из которых оставляем 15: сдвиг на 31. */
	ma = (u64)(ba & 0x007FFFFFu) | 0x00800000u;
	mb = (u64)(bb & 0x007FFFFFu) | 0x00800000u;
	m = (s32)((ma * mb) >> 31);
	if ((ba ^ bb) & 0x80000000u)
		m = -m;
	t.mantissa = m;
	t.lsb_exp = (ea - 127) + (eb - 127) - 15;
	return t;
}

float ge_row_sum(const struct GeRowTerm *terms, int count)
{
	int lsb_exp = -100000;
	int i;
	s32 sum = 0;

	for (i = 0; i < count; i++)
		if (terms[i].lsb_exp > lsb_exp)
			lsb_exp = terms[i].lsb_exp;

	for (i = 0; i < count; i++) {
		s32 m = terms[i].mantissa;
		int shift;

		if (m == 0)
			continue;
		shift = lsb_exp - terms[i].lsb_exp;
		/* Усечение к нулю при сдвиге вправо, как у GE. */
		if (shift < 32)
			sum += (m < 0) ? -(-m >> shift) : (m >> shift);
	}
	if (sum == 0)
		return 0.0f;
	return ge_truncate_float24(
		ge_scale_by_pow2_exact((float)sum, lsb_exp));
}

float ge_dot3(float ax, float ay, float az,
              float bx, float by, float bz)
{
	struct GeRowTerm t[3];

	t[0] = ge_product(ge_truncate_float24(ax),
	                  ge_truncate_float24(bx));
	t[1] = ge_product(ge_truncate_float24(ay),
	                  ge_truncate_float24(by));
	t[2] = ge_product(ge_truncate_float24(az),
	                  ge_truncate_float24(bz));
	return ge_row_sum(t, 3);
}

float ge_normalize3(float *v)
{
	float d2 = ge_dot3(v[0], v[1], v[2], v[0], v[1], v[2]);
	float r, len;

	if (!(d2 > 0.0f))
		return 0.0f;
	/* Денормал или бесконечность квадрата длины — не обрабатываем,
	 * как и оригинал: он возвращает 0 и оставляет вектор. */
	r = ge_rsqrt(d2);
	v[0] = ge_product_to_float24(
		(double)ge_truncate_float24(v[0]) * r);
	v[1] = ge_product_to_float24(
		(double)ge_truncate_float24(v[1]) * r);
	v[2] = ge_product_to_float24(
		(double)ge_truncate_float24(v[2]) * r);
	len = ge_product_to_float24((double)d2 * r);
	return len;
}

