float ge_rsqrt(float d)
{
	u32 bits = fbits(d);
	u32 i = (bits >> 8) & 0x7FFFu;
	int e = (int)((bits >> 23) & 0xFFu) - 127;
	const struct GeRecipSegment *seg =
		&ge_rsqrt_segments[e & 1][i >> 8];
	s32 q = (64 * seg->b + 63 + seg->m * (s32)(i & 255u)) >> 7;

	/* ScaleByPow2(q, -16 - (e >> 1), 0) — знак не нужен, d положительный. */
	return ge_scale_by_pow2((float)q, -16 - (e >> 1), 0);
}

