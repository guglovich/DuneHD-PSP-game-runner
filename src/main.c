/* Отдельная функция на ассемблере: менять указатель стеля внутри обычной
 * функции нельзя — компилятор считает его неизменным и в своём коде выхода
 * восстановил бы прежнее значение, то есть вернул бы управление в середину
 * гостя.
 *
 * `.set noreorder` обязателен: ассемблер по умолчанию переставляет инструкции
 * в слот задержки jr, и запись перед jr оказывалась после него.
 *
 * Кадр на 64 байта и восстановление `$s0`..`$s7`, `$fp`, `$ra` обязательны.
 * Переход в гостя — это прыжок, а не вызов, и ABI их не разделяет: гость
 * свободно портит всё, что считается callee-saved, и восстанавливает только
 * своё. Замер на плеере: гость отработал старт модуля (четыре импорта, создание
 * и запуск потока) и вернулся из точки входа — после чего `main` читал
 * `g_state` по разрушенному `$s1` и падал на `sw` по мусору. `$gp` не
 * подменяется: гость линкован как НЕ-PIC и обращений через `$gp` в нём нет.
 *
 * Промежуточные значения кладутся в $8 и $9, потому что после `move a1,a3`
 * в $5 лежит уже аргумент, а не вершина стека. */
/* Переход в гостя и выход из гостя.
 *
 * `.set noreorder` обязателен: ассемблер по умолчанию переставляет инструкции
 * в слот задержки jr, и запись перед jr оказывалась после него.
 *
 * **Возврата в `main` здесь нет и он не нужен.** Гость — это отдельный мир: он
 * портит `$s0`..`$s7`, `$fp`, `$sp` и `$gp`, и восстанавливает только своё.
 * Переход сюда — прыжок, а не вызов, и ABI их не разделяет. Две попытки
 * починить это сохранением регистров обе провалились, и обе — по одной причине,
 * измеренной на плеере: **гость затирает `$gp`**. Любое восстановление через
 * GOT (`la`, `lw …(%gp)`) после возврата читает по адресу из гостя, и `$s1`
 * восстанавливается мусором — `main` падает на `sw` по нулю.
 *
 * Поэтому после возврата гостя процесс просто завершается системным вызовом:
 * это не требует ни одного регистра. Тот факт, что гость дошёл до возврата,
 * и есть результат — стадия потомка в этот момент ещё равна 2.
 *
 * Промежуточные значения кладутся в $9 и $10: после сдвига аргументов в $4 и
 * $5 там лежат уже аргументы гостя, а не вершина стека. */
__asm__(
    "    .set noreorder\n"
    "    .text\n"
    "    .globl guest_enter\n"
    "    .type guest_enter, @function\n"
    "guest_enter:\n"
    "    move   $9, $4\n"      /* t1 = адрес гостевой точки входа */
    "    move   $10, $5\n"     /* t2 = вершина стека гостя */
    /* `$k0` — пятый аргумент, по ABI o32 он лежит в стеке вызова на
     * `16($sp)`, и читается ДО подмены `$sp` (она ниже).
     *
     * Зачем. Гость читает `$k0` как указатель и по нему пишет
     * (`0x08ABD018  sw $s5,4($k0)`), но НЕ ПИШЕТ В НЕГО НИ ОДНОЙ
     * инструкцией: проверено инструментом по обеим исполняемым секциям
     * (`.text` и `.sceStub.text`). Значит значение обязано прийти извне, и
     * единственное место, где мы его контролируем, — запуск потока.
     *
     * Адрес берётся из отображения гостя: гость по нему пишет, и хостский
     * адрес для него бессмыслен. `$k1` того же класса, передавать мусор хуже
     * нуля. */
    "    lw     $11, 16($sp)\n"
    "    move   $26, $11\n"
    "    move   $27, $0\n"
    /* $t8 и $t9 обнуляются обязательно.
     *
     * Переход сделан прыжком, а не вызовом, поэтому `$t9` гость наследует
     * от вызова `guest_enter` из C: там `$t9` = адрес самой `guest_enter`.
     * Замер на плеере в сбое потока: `t9 = 0x2AAAAFF0` — это ровно адрес
     * `guest_enter` в нашем образе, то есть гость держал в `$t9` адрес
     * хостского кода и предстоял `jalr $t9`. Свежий поток PSP таких значений
     * не наследует, поэтому обнуление здесь не подгонка, а воспроизведение
     * того состояния, которое поток должен получить. */
    "    move   $24, $0\n"
    "    move   $25, $0\n"
    "    move   $29, $10\n"    /* sp = вершина стека гостя */
    "    move   $4, $6\n"      /* a0 = первый аргумент гостя */
    "    move   $5, $7\n"      /* a1 = второй аргумент гостя */
    /* `$ra` обязан указывать на путь выхода, а не оставаться адресом возврата
     * в `main`: переход сделан обычным `jr`, и без этой записи гость,
     * завершив точку входа, возвращался `jr $ra` прямо в `main` — мимо
     * восстановления регистров, с порчей `$gp` и `$s1`. Метка локальная, она
     * разрешается ассемблером внутри этого же фрагмента. */
    "    la     $31, 1f\n"
    "    jr     $9\n"
    "    nop\n"
    "1:\n"
    "    li     $4, 0\n"
    "    li     $2, 4001\n"    /* v0 = __NR_exit, MIPS o32 */
    "    syscall\n"
    "    li     $2, 4001\n"
    "    syscall\n"
    "    .set reorder\n"
    "    .size guest_enter, .-guest_enter\n");

extern void guest_enter(u32 entry, u32 sp, u32 a0, u32 a1, u32 k0);

