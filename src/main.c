/*
 * PSP HLE Runtime — главный файл.
 *
 * Использование:
 *   psp-hle [--check] <путь_к_EBOOT.BIN>
 *
 * Что делает по порядку:
 *   1. читает файл образа;
 *   2. загружает его как гостевой модуль по базе 0x08804000 с релокациями;
 *   3. перечисляет импорты и ставит в каждый стаб ловушку;
 *   4. запускает точку входа в отдельном процессе.
 *
 * Почему ловушка, а не подмена адреса в стабе.
 *
 * Гостевой стаб — это 8 байт, помещающиеся в один 256 МБ сегмент, поэтому в
 * него можно только записать `j`. Прыжок на хостскую функцию не работает:
 * проверено на живом плеере, гость падает на первом же вызове импорта, хотя
 * цепочка записана верно — см. docs/guest-entry.md. Трамплин внутри гостя
 * тоже не помогает.
 *
 * Ловушка обходит это целиком. В стаб пишется `break 0`, и обработчик
 * SIGTRAP внутри гостевого исполнения выставляет $v0 — код возврата, который
 * PSP-функция обязана вернуть, — и заменяет ловушку на `jr $ra; nop`.
 * Перехода гостевого кода в наш код не происходит, поэтому состояние
 * регистров предсказуемо.
 *
 * Именно замена, а не сдвиг адреса инструкции. Замер на плеере показал: поле
 * PC находится в gregs[25], но записанное туда значение при возврате из
 * обработчика не восстанавливается, поэтому сдвинуть PC невозможно. Замена
 * же работает: после возврата процессор перечитывает инструкку по тому же
 * адресу, а там уже `jr $ra; nop`. Ловушка срабатывает один раз на стаб, а не
 * на каждый вызов. Подробности — tests/trap_probe.c и docs/trap-mechanism.md.
 *
 * Счётчики ведутся в разделяемой странице, и это не украшение.
 *
 * Гость исполняется в потомке, а отчёт печатает родитель. После fork
 * страницы памяти копируются, и запись потомка в свою копию родитель не
 * видит никогда. С обычными глобальными переменными родитель всегда
 * получал бы нули — и вывод «вызовов импортов обработано: 0» ничего не
 * значил бы, даже если бы ловушки работали. Все счётчики поэтому лежат в
 * MAP_SHARED-странице, и это же относится к индексу поля PC, который
 * находит потомок.
 */

