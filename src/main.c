/* Нужен, чтобы отчёт связывал вызов с местом в коде гостя. Индекс сквозной по
 * всем библиотекам, в том же порядке, что и при построении трамплинов, — иначе
 * адрес указывал бы на чужой стаб и выглядел бы правдоподобно. */
static u32 stub_addr_by_index(u32 index)
{
    u32 li, ii;
    u32 k = 0;

    for (li = 0; li < g_imports.count; li++) {
        for (ii = 0; ii < g_imports.libs[li].count; ii++) {
            if (k == index)
                return g_imports.libs[li].imports[ii].stub_runtime;
            k++;
        }
    }
    return 0;
}

