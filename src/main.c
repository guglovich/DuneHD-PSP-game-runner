int main(int argc, char **argv)
{
    g_thread_info_off = (getenv("NO_THREAD_INFO") != NULL);

    const char *path = NULL;
    bool check_only = false;
    /* Выгрузка окна загруженного гостя: `dump <файл> <адрес> <длина> <куда>`.
     *
     * Нужна потому, что дизасм ФАЙЛА неверен: к нему применены релокации, и
     * замер показал `lui v0, 0x002D` в файле против `lui v0, 0x08AD` в
     * памяти. А `objdump` без символьной таблицы врёт и больше того — он
     * показывает в модуле целую полосу `jr $ra; nop`, которой в загруженном
     * образе может не быть.
     *
     * Отдельный вызов обработчика не нужен: `guest_load` отрабатывает ДО
     * `fork`, поэтому у родителя уже есть отображение гостя с уже применёнными
     * релокациями — ровно то, что видел потомок. */
    bool dump_mode = false;
    u32 dump_addr = 0;
    u32 dump_len = 0;
    const char *dump_out = NULL;
    u8 *image;
    size_t image_size = 0;
    void *stack;
    u32 sp_top;
    /* Стек гостя выделяется с запасом сверху отведенного места, и гостю
     * отдаётся не вершина отображения, а точка ниже.
     *
     * Причина измерена: при вершине стека ровно на границе отображения
     * доставка сигнала в гостя обрывалась SIGSEGV, и si_addr равнялся
     * самой вершине — то есть кадр сигнала упирался в край отображения.
     * Повторялось при любом размере стека (256 КБ и 1 МБ), потому что
     * вершина всегда совпадала с границей.
     *
     * Отдельная проба на плеере работала при стеке, у которого вершина
     * далеко от края: процессорам MIPS при доставке сигнала нужен запас
     * рядом с вершиной. Здесь так и сделано: отдаётся 1 МБ рабочего места,
     * а сверху остаётся ещё 3 МБ. */
    const size_t STACK_RESERVE = 4u * 1024u * 1024u;
    const size_t STACK_COMMIT  = 1u * 1024u * 1024u;
    int status = 0;

    /* stdout на плеере не tty и потому буферизуется: при выводе в файл лог
     * выглядит пустым, пока процесс жив. Для разбора падений это неприемлемо. */
    setvbuf(stdout, NULL, _IONBF, 0);

    /* Флаг принимается в любой позиции: «--check PATH» и «PATH --check»
     * работают одинаково. Раньше читался только первый аргумент, и вызов
     * «PATH --check» молча запускал гостя вместо разбора. */
    /* Подкоманды установки плагина. Проверяются только как первый и
     * единственный аргумент: имя файла пользователь выбирает сам, и не должно
     * молча превращаться в команду. */
    if (argc == 2) {
        if (strcmp(argv[1], "install") == 0) {
            if (!psp_launcher_install()) {
                fprintf(stderr, "[MAIN] Плагин не установлен\n");
                return 1;
            }
            return 0;
        }
        if (strcmp(argv[1], "uninstall") == 0) {
            if (!psp_launcher_uninstall()) {
                fprintf(stderr, "[MAIN] Плагин не удалён\n");
                return 1;
            }
            return 0;
        }
        if (strcmp(argv[1], "status") == 0) {
            if (psp_launcher_is_installed())
                printf("плагин установлен\n");
            else
                printf("плагин не установлен\n");
            return psp_launcher_is_installed() ? 0 : 1;
        }
    }

    /* Подкоманда выгрузки окна гостя. */
    if (argc == 6 && strcmp(argv[1], "dump") == 0) {
        path = argv[2];
        dump_addr = (u32)strtoul(argv[3], NULL, 16);
        dump_len = (u32)strtoul(argv[4], NULL, 16);
        dump_out = argv[5];
        dump_mode = true;
        check_only = true;      /* гость не запускаем, только читаем память */
    }

    if (!dump_mode) {
        int i;
        for (i = 1; i < argc; i++) {
            if (strcmp(argv[i], "--check") == 0)
                check_only = true;
            else if (path == NULL)
                path = argv[i];
        }
    }
    if (path == NULL) {
        fprintf(stderr,
                "Использование: %s [--check] <файл>\n"
                "            %s install | uninstall | status\n"
                "Принимаются: EBOOT.BIN розничный (~PSP), EBOOT.BIN ELF,\n"
                "             ISO 9660 с EBOOT.BIN, CSO.\n",
                argv[0], argv[0]);
        return 1;
    }

    /* Разделяемая страница под счётчики: гость живёт в потомке, отчёт
     * печатает родитель, а после fork страницы копируются. */
    g_state = mmap(NULL, 65536, PROT_READ | PROT_WRITE,
                   MAP_SHARED | MAP_ANONYMOUS, -1, 0);
    if (g_state == MAP_FAILED) {
        fprintf(stderr, "[MAIN] Не удалось выделить разделяемую страницу\n");
        return 1;
    }
    memset((void *)g_state, 0, 65536);
    g_state->tramp_done = 0xFFFFFFFFu;   /* ни один трамплин не вернулся */
    g_state->pc_index = -1;
    g_state->guest_reg_index = -1;
    /* Смещение поля с адресом инструкции: -1, а не 0, потому что 0 означало бы
     * «поле найдено в самом начале контекста», а поле ещё не найдено. */
    g_state->trap_stub_off = -1;

    printf("========================================\n");
    printf("  PSP HLE Runtime для Dune HD Max\n");
    printf("  Sigma SMP8645, MIPS32 LE\n");
    printf("========================================\n\n");

    /* Образ ISO 9660 с игрой: сначала достать EBOOT.BIN.
     *
     * Автозапуск отдаёт лаунчеру тот файл, который открыли в файловом
     * менеджере, а открыть можно и образ. Раньше psp-hle на ISO просто
     * отказывался, то есть половина поддерживаемых форматов не работала
     * никогда.
     *
     * Критерий — наличие EBOOT.BIN в дереве образа, а не эвристика по
     * строке в первых секторах: она даёт неверный ответ в обе стороны. */
    if (psp_iso_is_game(path)) {
        PspIsoLayout layout;
        char err[256];

        printf("Образ ISO 9660 с EBOOT.BIN — извлекаю (%s)...\n",
               path);
        if (!psp_iso_extract_eboot(path, EXTRACTED_EBOOT, &layout, err,
                                  sizeof(err))) {
            fprintf(stderr, "[MAIN] Извлечение не удалось: %s\n", err);
            return 1;
        }
        printf("  EBOOT.BIN: %u Б из каталога %s, LBA %u\n",
               (unsigned)layout.eboot_size, layout.eboot_dir,
               (unsigned)layout.eboot_lba);
        path = EXTRACTED_EBOOT;
    }

    image = read_file(path, &image_size);
    if (image == NULL)
        return 1;

    /* Зашифрованный образ ~PSP расшифровывается прямо здесь.
     *
     * Раньше рантайм на таком файле печатал «сначала расшифровать» и
     * выходил с кодом 2. Для ручной проверки это удобно, но для автозапуска
     * означало, что розничная игра не запускается никогда: скрипт действия
     * вызывает psp-hle напрямую, и пользователю пришлось бы запускать
     * pspdecrypt руками перед каждым открытием файла. */
    if (psp_is_encrypted_eboot(image, image_size)) {
        u8 *plain;
        size_t plain_size = 0;
        const char *why = NULL;

        printf("Образ зашифрован схемой ~PSP — расшифровываю.\n");
        plain = psp_decrypt_eboot(image, image_size, &plain_size, &why);
        if (plain == NULL) {
            fprintf(stderr, "[MAIN] Расшифровка не удалась: %s\n", why);
            free(image);
            return 2;
        }
        printf("  расшифровано %u Б, первые байты: %02X %02X %02X %02X\n",
               (unsigned)plain_size, plain[0], plain[1], plain[2], plain[3]);
        free(image);
        image = plain;
        image_size = plain_size;
    }

    if (!guest_load(&g_mod, image, image_size, 0)) {
        fprintf(stderr, "[MAIN] Загрузка не удалась: %s\n", g_mod.error);
        free(image);
        return 1;
    }
    if (!guest_read_module_info(&g_mod, &g_info)) {
        fprintf(stderr, "[MAIN] Сведения о модуле не прочитаны\n");
        free(image);
        return 1;
    }
    if (!guest_scan_imports(&g_mod, &g_info, &g_imports)) {
        fprintf(stderr, "[MAIN] Импорты не перечислены: %s\n", g_mod.error);
        free(image);
        return 1;
    }

    printf("Модуль      : %s\n", g_info.name);
    printf("Гость       : 0x%08X .. 0x%08X (%u Б)\n", g_mod.base,
           g_mod.base + g_mod.span, g_mod.span);
    printf("Точка входа : 0x%08X\n", g_mod.base + g_mod.entry);
    printf("Релокаций   : %u из %u применено\n", g_mod.reloc_applied,
           g_mod.reloc_total);
    printf("Импортов    : %u в %u библиотеках\n", g_imports.total_imports,
           g_imports.count);
    printf("\n");

    /* Трамплины ставятся и в режиме выгрузки: иначе `dump` отдавал бы
     * исходные `jr $ra`, а не то, что реально исполняет гость. Проверено:
     * до этой правки стабы читались как `03E00008 00000000`, то есть
     * нетронутые. */
    /* Трамплины ставятся и в режиме выгрузки: иначе `dump` отдавал бы
     * исходные `jr $ra`, а не то, что реально исполняет гость. Проверено:
     * до этой правки стабы читались как `03E00008 00000000`, то есть
     * нетронутые.
     *
     * В обычном прогоне они ставятся ниже, после освобождения исходного
     * образа, — там это неважно, а здесь порядок единственный. */
    if (check_only) {
        u32 host_fn = (u32)(uintptr_t)&hle_import;
        u32 host_gp = 0;

        if (!gp_value(host_fn, &host_gp)) {
            fprintf(stderr, "[MAIN] Пролог hle_import не распознан\n");
            return 1;
        }
        if (!install_trampolines(host_fn, host_gp)) {
            fprintf(stderr, "[MAIN] Трамплины не построены: %s\n", g_mod.error);
            return 1;
        }
    }

    if (check_only) {
        if (dump_mode) {
            FILE *out = fopen(dump_out, "wb");
            u32 off;

            if (out == NULL) {
                fprintf(stderr, "[MAIN] Не открыть %s для записи\n", dump_out);
                return 1;
            }
            /* Граница — всё отображение, а не `span`: пул трамплинов лежит
             * после гостя, и выгрузка трамплина молча отвергалась как «вне
             * гостя». Проверено: адрес 0x08CA3500 в `span` не попадает. */
            if (dump_addr < g_mod.base || dump_len == 0 ||
                (u64)dump_addr + dump_len > (u64)g_mod.base + g_mod.map_size) {
                fprintf(stderr,
                        "[MAIN] Окно 0x%08X..0x%08X вне отображения "
                        "0x%08X..0x%08X\n",
                        dump_addr, dump_addr + dump_len, g_mod.base,
                        g_mod.base + g_mod.map_size);
                fclose(out);
                return 1;
            }
            off = dump_addr - g_mod.base;
            fwrite((const u8 *)g_mod.memory + off, 1, dump_len, out);
            fclose(out);
            printf("Выгружено 0x%08X..0x%08X (%u Б) из загруженного гостя в %s\n",
                   dump_addr, dump_addr + dump_len, dump_len, dump_out);
            guest_free_imports(&g_imports);
            guest_unload(&g_mod);
            free(image);
            return 0;
        }
        printf("--check: гость не запускается.\n");
        guest_free_imports(&g_imports);
        guest_unload(&g_mod);
        free(image);
        return 0;
    }

    /* Исходный образ больше не нужен: модуль уже скопирован в своё отображение
     * со всеми применёнными релокациями. Освобождаем сразу, а не в конце
     * прогона. На плеере это 5,6 МБ из `MemFree`, который там держится в
     * пределах 15 МБ, и лишние 5,6 МБ во время исполнения гостя — прямой риск
     * нехватки памяти под его стеки. */
    free(image);
    image = NULL;

    {
        u32 host_fn = (u32)(uintptr_t)&hle_import;
        u32 host_gp = 0;

        if (!gp_value(host_fn, &host_gp)) {
            fprintf(stderr,
                    "[MAIN] Пролог hle_import не распознан, $gp неизвестен\n");
            return 1;
        }
        if (!install_trampolines(host_fn, host_gp)) {
            fprintf(stderr, "[MAIN] Трамплины не построены: %s\n",
                    g_mod.error);
            return 1;
        }
    }
    install_handlers();

    /* Адреса стабов потоков — обработчик сопоставляет их сравнением, без
     * вызовов. */
    g_state->stub_create_thread = find_stub_by_nid(0x446D8DE6u);
    g_state->stub_start_thread = find_stub_by_nid(0xF475845Du);

    stack = mmap(NULL, STACK_RESERVE, PROT_READ | PROT_WRITE,
                 MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    if (stack == MAP_FAILED) {
        fprintf(stderr, "[MAIN] Не удалось выделить стек гостя\n");
        return 1;
    }
    sp_top = (u32)(uintptr_t)stack + STACK_COMMIT;
    /* База загрузки нужна для разбора адресов сбоя: бинарник Position
     * Independent, и в дампе адреса от нуля, а в сбое они от базы. Без неё
     * адрес из `ucontext` невозможно сопоставить с функцией. */
    {
        Dl_info di;

        if (dladdr((void *)(uintptr_t)&main, &di) != 0 &&
            di.dli_fbase != NULL) {
            g_self_base = (u32)(uintptr_t)di.dli_fbase;
            printf("База образа  : %p (main по файлу 0x%08X)\n", di.dli_fbase,
                   (u32)(uintptr_t)&main - (u32)(uintptr_t)di.dli_fbase);
        }
    }

    printf("Стек гостя   : рабочая часть 0x%08X .. 0x%08X\n",
           (u32)(uintptr_t)stack, sp_top);
    printf("Запас сверху : 0x%08X .. 0x%08X (%u КБ)\n", sp_top,
           (u32)(uintptr_t)stack + STACK_RESERVE,
           (unsigned)((STACK_RESERVE - STACK_COMMIT) / 1024));
    printf("Данные без EXEC : %s (смещение 0x%08X)\n",
           g_mod.data_protected ? "да" : "НЕТ", g_mod.data_off);
    printf("Разбор секций  : shnum=%u entsize=%u shoff=0x%08X кандидатов=%u причина=%u\n",
           g_mod.sec_diag[0], g_mod.sec_diag[1], g_mod.sec_diag[2],
           g_mod.sec_diag[3], g_mod.sec_diag[4]);
    printf("sigaltstack  : не используется\n\n");

    printf("Запуск гостя (предел %d с)...\n", GUEST_TIMEOUT_SEC);

    {
        pid_t pid = fork();

        if (pid < 0) {
            fprintf(stderr, "[MAIN] fork не удался\n");
            return 1;
        }
        if (pid == 0) {
            g_state->child_pid = (unsigned long)getpid();
            g_state->child_stage = 1;
            alarm(GUEST_TIMEOUT_SEC);
            g_state->child_stage = 2;
            /* Возврата отсюда не бывает: guest_enter сам завершает процесс,
             * когда гость дошёл до конца своей точки входа. Стадия 3
             * недостижима и оставлена только как страховка на случай, если
             * вызов всё же вернётся. */
            guest_enter(g_mod.base + g_mod.entry, sp_top, 0, 0, 0);
            g_state->child_stage = 3;
            _exit(0);
        }
        if (waitpid(pid, &status, 0) < 0) {
            fprintf(stderr, "[MAIN] waitpid не удался\n");
        } else if (WEXITSTATUS(status) == 90) {
            printf("СБОЙ: сигнал %d, si_addr 0x%08X\n", g_state->fault_sig,
                   g_state->fault_addr);
            printf("      сбой в pid %lu, потомок pid %lu, стадия %d\n",
                   g_state->fault_pid, g_state->child_pid,
                   g_state->child_stage);
            if (g_state->fault_addr >= (u32)(uintptr_t)stack &&
                g_state->fault_addr < (u32)(uintptr_t)stack + STACK_RESERVE)
                printf("      si_addr внутри стека гостя\n");
            else if (g_state->fault_addr >= g_stub_lo &&
                     g_state->fault_addr < g_stub_hi)
                printf("      si_addr внутри области стабов\n");
            else
                printf("      si_addr вне стека и вне стабов\n");
            if (g_state->regs_valid) {
                u32 pc = g_state->regs[FAULT_PC_REG];
                u32 sp = g_state->regs[SP_REG];

                printf("      PC (+0x%X)  = 0x%08X%s\n",
                       FAULT_PC_OFFSET, pc,
                       (pc >= g_mod.base && pc < g_mod.base + g_mod.span)
                           ? "  — в госте"
                           : "  (вне гостя)");
                printf("      SP (gregs[%d])   = 0x%08X\n", SP_REG, sp);
                if (g_state->guest_reg_index >= 0)
                    printf("      перебором найден 0x%08X в gregs[%d]\n",
                           g_state->guest_reg_hit, g_state->guest_reg_index);
                else
                    printf("      перебором ничего не найден в госте\n");
                if (g_self_base != 0 && pc >= g_self_base &&
                    pc < g_self_base + SELF_SPAN)
                    printf("      PC — в НАШЕМ образе, файловое смещение 0x%05X\n",
                           pc - g_self_base);
                else
                    printf("      PC — вне нашего образа\n");
                if (g_state->insn_valid)
                    printf("      инструкция: %08X %08X %08X %08X\n",
                           g_state->insn[0], g_state->insn[1],
                           g_state->insn[2], g_state->insn[3]);
            }
            printf("      входов в обработчик ловушки: %lu\n",
                   g_state->traps_entered);
            printf("      контекст, переданный обработчику: 0x%08X\n",
                   g_state->trap_ctx);
        } else if (WIFSIGNALED(status)) {
            printf("Гость прерван сигналом %d\n", WTERMSIG(status));
        } else if (g_state->child_stage == 2) {
            /* Стадия 2 и штатный код 0 — это и есть возврат гостя из точки
             * входа: он отработал модульный старт и дошёл до конца. */
            printf("Гость ВЕРНУЛСЯ из точки входа, код %d\n",
                   WEXITSTATUS(status));
            printf("  модульный старт отработал; следующий шаг — реализация "
                   "потоков, иначе созданный поток не выполняется\n");
        } else {
            printf("Гость вышел, код %d, стадия %d\n", WEXITSTATUS(status),
                   g_state->child_stage);
        }
    }

    /* Поток гостя. Модульный старт только создал его и попросил запустить, а
     * сам исполниться ему негде: точка входа гостя возвращается. Поэтому
     * функция потока запускается здесь, отдельным потомком — родитель после
     * этого остаётся цел, а `guest_enter` без возврата в C работать не должен. */
    if (g_state->thread_started && g_state->thread_entry != 0) {
        void *tstack;
        pid_t tpid;

        printf("\nПоток гостя: функция 0x%08X\n", g_state->thread_entry);

        /* Вершина стека печатается ПОСЛЕ выделения: в первом варианте печать
         * стояла выше `mmap`, и показывала неинициализированный `tstack`,
         * то есть `0x00000000 + STACK_COMMIT`. Выглядело как «рантайм запускает
         * поток на стеке по адресу 0x100000» — правдоподобно и неверно. */
        tstack = mmap(NULL, STACK_RESERVE, PROT_READ | PROT_WRITE,
                      MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
        if (tstack == MAP_FAILED) {
            fprintf(stderr, "[MAIN] Не удалось выделить стек потока\n");
        } else {
            printf("            стек потока 0x%08X, вершина 0x%08X\n",
                   (unsigned)(uintptr_t)tstack,
                   (unsigned)(uintptr_t)tstack + STACK_COMMIT);
            pid_t p2 = fork();

            if (p2 == 0) {
                alarm(GUEST_TIMEOUT_SEC);
                guest_enter(g_state->thread_entry,
                            (u32)(uintptr_t)tstack + STACK_COMMIT, 0, 0,
                            g_thread_info_addr(NULL));
                g_state->thread_ran = 2;
                _exit(0);
            }
            tpid = p2;
            if (tpid < 0) {
                fprintf(stderr, "[MAIN] fork потока не удался\n");
            } else if (waitpid(tpid, &status, 0) < 0) {
                fprintf(stderr, "[MAIN] waitpid потока не удался\n");
            } else if (WIFSIGNALED(status)) {
                printf("Поток прерван сигналом %d\n", WTERMSIG(status));
                g_state->thread_ran = 1;
            } else if (WEXITSTATUS(status) == 90) {
                /* Код 90 ставит guest_fault: поток упал, и разбирать это нужно
                 * с диагностикой, а не одним числом. */
                g_state->thread_ran = 1;
                print_fault_short("потоке гостя");
            } else {
                printf("Поток вышел, код %d\n", WEXITSTATUS(status));
                g_state->thread_ran = 2;
            }
        }
    }


    printf("\nВызовов импортов обработано: %lu\n", g_state->calls);
    printf("  из них без реализации:      %lu\n", g_state->unknown);
    printf("Поле PC в ucontext:             %d байт от начала контекста\n",
           g_state->trap_stub_off);

    /* Список вызовов. Аргументы поимённо — по измеренным смещениям. */
    {
        printf("\nВызовы импортов:\n");
        unsigned long k;
        int t;

        for (k = 0; k < g_state->calls && k < STUB_LOG_SIZE; k++) {
            u32 idx = g_state->stubs[k];
            u32 nid = (idx < HLE_MAX_IMPORTS) ? g_hle_nid[idx] : 0;
            u32 stub = stub_addr_by_index(idx);

            t = (int)k;
            /* Печатаются индекс, NID и адрес стаба в госте. Индекс даёт
             * трамплин, NID — имя функции в data/psp_nids.tsv, а адрес стаба
             * связывает вызов с местом в разобранном коде гостя, откуда он
             * был сделан. Имя в рантайме не хранится, таблица с ним для
             * отчёта не связана. */
            printf("  %3lu: импорт %3u  стаб 0x%08X  NID 0x%08X%s\n",
                   k + 1, idx, stub, nid,
                   is_implemented(nid) ? "  (есть реализация)"
                                       : "  (нет реализации)");
            /* Аргументы снимаются только для первых CTX_DUMP_TRAPS вызовов,
             * дальше снимок не ведётся. */
            if (k >= CTX_DUMP_TRAPS)
                continue;
            printf("        $a0=0x%08X  $a1=0x%08X  $a2=0x%08X  $a3=0x%08X\n",
                   g_state->args[t][0], g_state->args[t][1],
                   g_state->args[t][2], g_state->args[t][3]);
            printf("        стековые: 0x%08X 0x%08X 0x%08X"
                   "   $k0=0x%08X  pid=%u\n",
                   g_state->args[t][4], g_state->args[t][5],
                   g_state->args[t][6], g_state->args[t][7],
                   g_state->args[t][8]);
            printf("        место вызова (адрес возврата) = 0x%08X\n",
                   g_state->args[t][9]);
            /* Сверка `$ra`: значение из аргумента C и слово, реально лежащее в
             * кадре трамплина по адресу `$sp+0`. Расхождение означает, что
             * трамплин или путь возврата читаются не там, где мы думаем. */
            printf("        кадр: [$sp+0]=0x%08X  [$sp+4]=0x%08X\n",
                   g_state->args[t][10], g_state->args[t][11]);
            /* Команды по месту вызова: `jal` стоит за 8 байт до адреса
             * возврата, в слоте задержки — инструкция после неё.
             *
             * Зачем. Измерение дало неразрешимое противоречие: захват
             * аргументов доказанно исправен (подстановка `$a2` видна в
             * отчёте), значит гость имеет `$a1` = адрес возврата, но и
             * выгрузка загруженного образа, и Ghidra показывают
             * `addiu $a1,v0,-12440` прямо перед вызовом, без ветки, способной
             * её пропустить. Возможная причина — исполняемый сейчас код не тот,
             * что лежит в образе на диске (файл и загруженный образ уже
             * расходятся на `0x10000` на `HI16`).
             *
             * Чтение безопасно: это обычный контекст, не обработчик сигнала.
             * Если слово по `ra-8` не равно `0x0C...` (то есть не `jal`), код
             * исполняется не тот, и статический разбор непригоден вовсе. */
            {
                /* `ra` лежит в снимке: слот 9 — это четвёртый аргумент
                 * `hle_import`, то есть адрес возврата из гостя. */
                u32 ra_addr = g_state->args[t][9];
                const u32 *call = (const u32 *)(uintptr_t)(ra_addr - 8);
                const u32 *ret  = (const u32 *)(uintptr_t)ra_addr;
                printf("        команда: [ra-8]=0x%08X  [ra]=0x%08X\n",
                       *call, *ret);
            }
            {
                int f;
                printf("        весь кадр:");
                for (f = -8; f < 16; f++)
                    printf(" sp%+d=0x%08X", f * 4, g_state->frame[t][f + 8]);
                printf("\n");
            }
        }
        if (k > 0)
            printf("\nГость исполнял код и вызывал импорты.\n");
    }

    guest_free_imports(&g_imports);
    guest_unload(&g_mod);
    free(image);      /* безвредно: в ветках исполнения уже NULL */
    return 0;
}