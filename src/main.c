static u8 *read_file(const char *path, size_t *size_out)
{
    FILE *f = fopen(path, "rb");
    u8 *buf;
    long size;

    if (f == NULL) {
        fprintf(stderr, "[MAIN] Не удалось открыть %s\n", path);
        return NULL;
    }
    if (fseek(f, 0, SEEK_END) != 0) {
        fclose(f);
        return NULL;
    }
    size = ftell(f);
    if (size <= 0 || fseek(f, 0, SEEK_SET) != 0) {
        fprintf(stderr, "[MAIN] Пустой или нечитаемый файл: %s\n", path);
        fclose(f);
        return NULL;
    }
    buf = malloc((size_t)size);
    if (buf == NULL) {
        fclose(f);
        return NULL;
    }
    if (fread(buf, 1, (size_t)size, f) != (size_t)size) {
        fprintf(stderr, "[MAIN] Ошибка чтения %s\n", path);
        free(buf);
        fclose(f);
        return NULL;
    }
    fclose(f);
    *size_out = (size_t)size;
    return buf;
}


