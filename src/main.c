/* Куда класть EBOOT.BIN, извлечённый из образа ISO. Каталог /tmp на плеере —
 * tmpfs, то есть в NAND ничего не попадает. */
#define EXTRACTED_EBOOT "/tmp/psp_launcher_eboot.bin"

/* Предел времени на гостя: без него зациклившийся код не остановится. */
#define GUEST_TIMEOUT_SEC 20

/* Сколько адресов последних срабатываний запоминаем. */
#define STUB_LOG_SIZE 128

/* Размер gregs[] в ucontext: ровно 32. Определено измерением — компилятор
 * адресует элементы с шагом 8, и чтение за 32-м выходит за массив. */
#define GREG_COUNT 32

/* Сколько байт контекста просматривается в поиске адреса инструкции.
 * Сигнальный кадр на MIPS занимает несколько сотен байт, 1024 с запасом. */
#define STUB_SCAN_BYTES 1024

/* Размер и глубина снимка контекста: слова и число первых ловушек. */
#define CTX_DUMP_WORDS 128
#define CTX_DUMP_TRAPS 8

/* Поле PC в ucontext.
 *
 * Смещение ИЗМЕРЕНО пробой `tests/uctx_segv.c` на плеере, отдельно для двух
 * видов сбоя:
 *
 *   | вид сбоя            | +0x20 | +0x40 | +0xF0 |
 *   |---------------------|-------|-------|-------|
 *   | по данным           |   PC  |   PC  |   PC  |
 *   | по выборке команды   | мусор |   PC  |   PC  |
 *
 * То есть **+0xF0 — единственное поле, верное в обоих случаях**, и читать
 * надо его.
 *
 * Прежнее значение 32 было верным только для сбоя по данным, откуда и шли
 * нестыкуемые числа в отчёте (`0x08ABD018`, `0x08ABD01C`, `0x08ABD014` при
 * одном и том же падении): при выборке команды на месте +0x20 лежит
 * содержимое регистра, а не адрес. */
#define FAULT_PC_OFFSET 0xF0

/* Смещения полей контекста В БАЙТАХ. Измерены пробой tests/uctx_layout.c:
 * гостевой код загружает в регистры заранее известные значения, обработчик
 * находит их в контексте, и смещение определяется фактом. Значения НЕ выведены
 * из заголовка musl — там раскладка другая.
 *
 * Все они кратны `CTX_GREGS_BASE + 8 * index`, то есть элементы `gregs[]`
 * идут с шагом 8 байт начиная с 40. Проверка согласованности: `$gp` =
 * 40 + 8*28 = 264, и проба нашла его именно там.
 *
 * Смещения, а не индексы, обязательны: `gregs[i]` — это 8 байт, и обращение
 * `((u32 *)ctx)[i]` взяло бы вместо поля i байт со смещения 4*i. Первая версия
 * была написана именно так и печатала 0x00000002 во всех аргументах. */
#define CTX_GREGS_BASE 40
#define CTX_V0  (CTX_GREGS_BASE + 8 * 2)    /* 56 */
#define CTX_A0  (CTX_GREGS_BASE + 8 * 4)    /* 72 */
#define CTX_A1  (CTX_GREGS_BASE + 8 * 5)    /* 80 */
#define CTX_A2  (CTX_GREGS_BASE + 8 * 6)    /* 88 */
#define CTX_A3  (CTX_GREGS_BASE + 8 * 7)    /* 96 */
#define CTX_GP  (CTX_GREGS_BASE + 8 * 28)   /* 264 */

/* Полное соответствие индексов и имён регистров.
 *
 * `gregs[i]` — это `pt_regs[i-1]`, то есть со сдвигом на один: `gregs[0]` в
 * musl занят чем-то своим, а дальше порядок MIPS как в `pt_regs`:
 * at, v0, v1, a0, a1, a2, a3, t0..t7, s0..s7, t8, t9, k0, k1, gp, sp, fp, ra.
 *
 * Согласуется с измерениями: `$gp` = 28 → 264 (проба нашла там),
 * `$a0` = 4 → 72 (проба нашла там), `$ra` = 31 → 288 (в снимке гостя там
 * адрес текста гостя).
 *
 * Прежние подписи в отчёте о сбое были неверны: `gregs[26]` помечался как
 * `$t9`, а по этому соответствию это **`$k0`**, и он равен 0. Именно это и
 * сбивало разбор: гостевой код проверяет `$k0` на ноль, и «нулевой `$t9`»
 * был на деле нулевым `$k0`. */
#define R_AT  1
#define R_V0  2
#define R_A0  4
#define R_A3  7
#define R_T0  8
#define R_T9  25
/* Регистров 26 и 27 (`$k0`, `$k1`) в раскладке НЕТ: между `$t9` и `$gp` нет
 * ни одного смещения. Измерено пробой на плеере, см. tests/uctx_layout.c.
 * Определять их номера здесь бессмысленно — читать нечего. */
#define R_GP_I 28
#define R_SP  29
#define R_FP  30
#define R_RA  31
/* Индексы для regs[]: PC кладётся последним, чтобы не вытеснять ничего. */
#define FAULT_PC_REG 32
#define SP_REG 29

/* Код возврата по умолчанию для импорта без реализации. */
#define MIPS_NOP_WORD   0x00000000u

