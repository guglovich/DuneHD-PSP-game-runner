/* Диагностика сбоя                                                           */
/* ------------------------------------------------------------------------- */

/* Без неё падение выглядит одинаково при любой причине: «прерван сигналом
 * 11». si_addr при сбое по выборке команды на MIPS равен нулю, поэтому
 * дополнительно ищется поле с адресом инструкции среди гостевых адресов. */
static void guest_fault(int sig, siginfo_t *si, void *ctx)
{
    unsigned i;
    int in_self, in_guest;

    g_state->fault_sig = sig;
    g_state->fault_addr = (u32)(uintptr_t)si->si_addr;
    g_state->fault_pid = (unsigned long)getpid();

    /* Регистры читаются по измеренным смещениям: `gregs[i]` — это 8 байт на
     * 40 + 8*i, обращение `((u32 *)ctx)[i]` взяло бы 4*i байт. */
    for (i = 0; i < GREG_COUNT; i++)
        g_state->regs[i] = *(const volatile u32 *)(const void *)
                           ((const u8 *)ctx + CTX_GREGS_BASE + 8 * i);
    /* PC берётся со смещения 32 — измерением на плеере установлено, что там
     * лежит адрес инструкции. Важно: для SIGSEGV это поле недостоверно, см.
     * docs/guest-entry.md; приводится ради полноты, и в отчёте помечается
     * отдельно. */
    /* Чтение напрямую, а не через memcpy: обработчик сигнала не вызывает
     * функций, `$t9` в нём равен 0. */
    g_state->regs[FAULT_PC_REG] =
        *(const volatile u32 *)(const void *)((const u8 *)ctx + FAULT_PC_OFFSET);
    g_state->pc_offs[0] =
        *(const volatile u32 *)(const void *)((const u8 *)ctx + 0x20);
    g_state->pc_offs[1] =
        *(const volatile u32 *)(const void *)((const u8 *)ctx + 0x40);
    g_state->pc_offs[2] =
        *(const volatile u32 *)(const void *)((const u8 *)ctx + FAULT_PC_OFFSET);
    g_state->regs_valid = 1;

    /* Проход по стеку гостя: слова, попадающие в образ гостя, — это сохранённые
     * адреса возврата. Даёт цепочку вызовов на момент сбоя.
     *
     * Нужен потому, что PC из кадра сигнала для этого сбоя не извлекается, а
     * больше взять нечего: `si_addr` = 0 говорит лишь, что прыжок был по нулю.
     *
     * В обработчике сигнала НЕЛЬЗЯ вызывать функции (`$t9` = 0), поэтому цикл
     * идёт напрямую по `volatile`, без `memcpy` и без `printf`. */
    {
        const volatile u32 *sp =
            (const volatile u32 *)(uintptr_t)g_state->regs[R_SP];
        unsigned n = 0;

        for (i = 0; i < BT_SCAN_WORDS && n < BT_MAX; i++) {
            u32 v = sp[i];

            if (v >= g_mod.base && v < g_mod.base + g_mod.span) {
                g_state->bt[n] = v;
                g_state->bt_word[n] = (u32)i;
                n++;
            }
        }
        g_state->bt_count = n;
    }

    for (i = 0; i < GREG_COUNT; i++) {
        u32 v = g_state->regs[i];
        if (v >= g_mod.base && v < g_mod.base + g_mod.span) {
            g_state->guest_reg_hit = v;
            g_state->guest_reg_index = (int)i;
            break;
        }
    }

    /* Слова инструкции по адресу сбоя — из своего образа ИЛИ из гостя.
     *
     * Гость тоже нужен: пока читалось только наше изображение, падение потока
     * осталось без опознания. Сравнение с файлом обязательно — загруженный
     * образ отличается от файла, к нему применены 233235 релокаций, и HI16/LO16
     * меняют непосредственные операнды `lui`/`addiu`. */
    /* Адрес инструкции сбоя: из поля по смещению 32.
 *
 * Для SIGTRAP это поле и есть PC.
 *
 * Для SIGSEGV поле НЕПРИГОДНО — проверено тремя прогонами подряд: при одном и
 * том же сбое (запись по нулевому `$k0`) оно содержало то `0x08ABD018`, то
 * `0x08ABD01C`, то `0x08ABD014`, и `si_addr` при этом тоже различался (`0x04`
 * и `0x00`) — то есть сбоит гостя два разных места. Прежняя попытка объявить
 * это «PC минус 4» была поспешной: из двух-трёх совпадений подряд закономерность
 * не следует, а печать «PC в госте» была бы уверенным неверным выводом.
 *
 * Локализует сбой `si_addr` — для сбоя по данным он достоверен: `0x04`
 * означает запись по `$k0 + 4`, то есть по нулевому `$k0`.
 *
 * Для SIGILL поле смысла не имеет: оно указывало на строку формата в
 * `.rodata` (`64615F69 30207264 38302578` = `i_ad`, `0 rd`, `80(x`), то есть
 * читать по нему нечего. Именно это породило прежний вывод «трамплин
 * исполняет мусор». */
    if (sig == SIGTRAP) {
        u32 pc = g_state->regs[FAULT_PC_REG];

        in_self = (g_self_base != 0 && pc >= g_self_base &&
                   pc < g_self_base + SELF_SPAN);
        in_guest = (pc >= g_mod.base && pc < g_mod.base + g_mod.span);

        g_state->insn_where = in_self ? 1 : (in_guest ? 2 : 0);
        if (in_self || in_guest) {
            const u32 *w = (const u32 *)(uintptr_t)(pc & ~3u);

            for (i = 0; i < 4; i++)
                g_state->insn[i] = w[i];
            g_state->insn_valid = 1;
        }
    }

    _exit(90);
}

/* Атрибуция NID делается в родителе, а не в обработчике: обработчик не может
 * вызвать ни одной функции — `$t9` в нём равен 0, см. trap_flush_icache.
 * Ограничение — записано только STUB_LOG_SIZE адресов стабов. */
/* Компактные диагностики сбоя.
 *
 * Отдельная функция, а не перенос существующего блока: у полной диагностики
 * другой формат и другая область видимости, и перенос её целиком затрагивал бы
 * работающий код. Здесь только то, без чего падение не опознать: сигнал,
 * адрес, где остановился процессор, и четыре слова инструкции по этому
 * адресу. */
static void print_fault_short(const char *who)
{
    u32 pc = g_state->regs[FAULT_PC_REG];

    printf("\nСБОЙ в %s: сигнал %d, si_addr 0x%08X\n", who,
           g_state->fault_sig, g_state->fault_addr);
    /* Смещение 32 достоверно только для SIGTRAP. Для остальных сигналов это
     * поле не адрес инструкции, и печатать его как PC значит выдать
     * произвольное слово за место сбоя. Помечаем явно, см. guest_fault. */
    printf("      PC (+0x%X)  = 0x%08X\n", FAULT_PC_OFFSET, pc);
    /* si_addr для сбоя по данным достоверен, в отличие от поля выше. Именно он
     * указал на запись по `$k0 + 4`, то есть по нулевому указателю. */
    if (g_state->fault_sig == SIGSEGV || g_state->fault_sig == SIGBUS)
        printf("      si_addr    = 0x%08X  <- достоверный адрес сбоя%s\n",
               g_state->fault_addr,
               g_state->fault_addr < 0x1000u
                   ? " (запись по почти нулевому указателю)" : "");
    /* Подписи регистров — измеренное соответствие `gregs[i]` = `pt_regs[i-1]`.
     * Прежние подписи называли `$t9` то, что на деле `$k0`, и из-за этого
     * разбор сбивался. */
    printf("      at=0x%08X v0=0x%08X  a0=0x%08X a1=0x%08X\n",
           g_state->regs[R_AT], g_state->regs[R_V0], g_state->regs[R_A0],
           g_state->regs[R_A0 + 1]);
    printf("      a2=0x%08X a3=0x%08X t0=0x%08X\n", g_state->regs[R_A0 + 2],
           g_state->regs[R_A3], g_state->regs[R_T0]);
    printf("      t9=0x%08X\n", g_state->regs[R_T9]);
    /* `$k0` и `$k1` НЕ печатаются: их нет в кадре сигнала. Измерено пробой
     * tests/uctx_layout.c на плеере — между `$t9` (+240) и `$gp` (+264) нет
     * смещений 248 и 256, то есть в ucontext этих регистров просто нет.
     *
     * Прежде здесь печатались `regs[26]` и `regs[27]`, и они выходили нулём.
     * Ноль был выдан за «регистр равен нулю» и на нём построен вывод о записи
     * по нулевому указателю — а это был просто разрыв в раскладке. */
    printf("      k0/k1      = ОТСУТСТВУЮТ в кадре сигнала (измерено)\n");
    printf("      gp=0x%08X sp=0x%08X fp=0x%08X ra=0x%08X\n",
           g_state->regs[R_GP_I], g_state->regs[R_SP], g_state->regs[R_FP],
           g_state->regs[R_RA]);
    if (g_self_base != 0 && pc >= g_self_base && pc < g_self_base + SELF_SPAN)
        printf("      поле +%d указывает в наш образ, файловое смещение 0x%05X%s\n",
               FAULT_PC_OFFSET, pc - g_self_base,
               g_state->fault_sig == SIGTRAP ? "" : "  (но это НЕ адрес инструкции)");
    if (g_state->insn_valid)
        printf("      инструкция (%s): %08X %08X %08X %08X\n",
               g_state->insn_where == 1 ? "наш образ"
                                        : "гость, по месту в памяти",
               g_state->insn[0], g_state->insn[1], g_state->insn[2],
               g_state->insn[3]);
    /* Индекс последнего импорта, чей трамплин вернулся в гостя. Отвечает
     * прямо на вопрос «падает ли гость внутри трамплина или уже в своём
     * коде»: без этой метки по отчёту это не определить. */
    printf("      трамплин вернулся по импорту: %u\n",
           g_state->tramp_done == 0xFFFFFFFFu ? 0 : g_state->tramp_done + 1);
    /* Цепочка вызовов гостя на момент сбоя: слова стека, попавшие в образ
     * гостя, — это сохранённые адреса возврата. */
    if (g_state->bt_count > 0) {
        int b;

        printf("      цепочка вызовов (%d):\n", g_state->bt_count);
        for (b = 0; b < g_state->bt_count; b++)
            printf("        sp+%03d  0x%08X\n", g_state->bt_word[b],
                   g_state->bt[b]);
    } else {
        printf("      цепочка вызовов: пусто (в стеке нет адресов образа госта)\n");
    }
    printf("      входов в обработчик ловушки: %lu\n", g_state->traps_entered);
    printf("      вызовов импортов: %lu\n", g_state->calls);
}

/* Адрес стаба по NID. Вызывается только родителем: обработчик сигнала функций
 * не вызывает, `$t9` в нём равен 0. */
static u32 find_stub_by_nid(u32 nid)
{
    u32 li, ii;

    for (li = 0; li < g_imports.count; li++)
        for (ii = 0; ii < g_imports.libs[li].count; ii++)
            if (g_imports.libs[li].imports[ii].nid == nid)
                return g_imports.libs[li].imports[ii].stub_runtime;
    return 0;
}


