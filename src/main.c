/* Порядок выбора сделан по измеренной частоте вызовов
 * (docs/import-call-analysis.md): сначала семафоры, они дают около 28 % всех
 * вызовов. Пока реализованы немногие, и все возвращают 0 — этого хватает,
 * чтобы гость не уходил в бесконечный цикл опроса состояния. */
static bool is_implemented(u32 nid)
{
    switch (nid) {
    /* Привод. Диска на плеере нет, и ответ «готов» необходим: наблюдалось
     * 2,6 млн вызовов sceUmdGetDriveStat подряд, то есть бесконечный цикл. */
    case 0x8EF08FCEu:   /* sceUmdWaitDriveStat */
    case 0x6B4A146Cu:   /* sceUmdGetDriveStat */
    /* Семафоры. */
    case 0x3F53E640u:   /* sceKernelSignalSema */
    case 0x4E3A1105u:   /* sceKernelWaitSema */
    case 0xD6DA4BA1u:   /* sceKernelCreateSema */
    case 0x28B6489Cu:   /* sceKernelDeleteSema */
    case 0x58B1F937u:   /* sceKernelPollSema */
    case 0xBC6FEBC5u:   /* sceKernelReferSemaStatus */
    /* Потоки гостя: без них игровой цикл не выполняется никогда. Настоящего
     * планировщика нет — функция потока запускается после возврата гостя из
     * точки входа, отдельным потомком. */
    case 0x446D8DE6u:   /* sceKernelCreateThread */
    case 0xF475845Du:   /* sceKernelStartThread */
    /* Прерывания: результата не возвращают, обработчик отдаёт 0 — этого
     * достаточно. Регистрация потока через них проходит: вызовы 6 и 7
     * (CpuSuspendIntr, CpuResumeIntr) видны в отчёте, и гость продолжает
     * выполнение после них. */
    case 0x092968F4u:   /* sceKernelCpuSuspendIntr */
    case 0x5F10D406u:   /* sceKernelCpuResumeIntr */
    /* Ожидание кадра. */
    case 0x984C27E7u:   /* sceDisplayWaitVblankStart */
    /* Задержка: без неё циклы крутятся без остановки. */
    case 0xCEADEB47u:   /* sceKernelDelayThread */
    /* Версия SDK: значение гостю не нужно, но вызов должен пройти. */
    case 0x7591C7DBu:   /* sceKernelSetCompiledSdkVersion */
    case 0xF77D77CBu:   /* SysMemUserForUser, имя не найдено; второй вызов при
                         * старте, без него гость не стартует вовсе */
        return true;
    default:
        return false;
    }
}

