/* Подстановка импортов трамплинами                                           */
/* ------------------------------------------------------------------------- */

/* Номер импорта -> NID. Заполняется при загрузке, читается обработчиком
 * вызова, который вызывается из гостя по трамплину.
 *
 * Предел выводится из ёмкости пула трамплинов, а не подбирается. Прежнее
 * `256` молча обрывало установку на 257-м импорте, а у LocoRoco 2 их 269 —
 * инструмент падал с «слишком много импортов: 256» и не давал снять образ
 * гостя, то есть блокировал собственную диагностику. Тот же дефект был в
 * `src/plugin/guest_run.c`. */
#define HLE_MAX_IMPORTS (GUEST_TRAMP_SIZE / GUEST_TRAMP_BYTES)
static u32 g_hle_nid[HLE_MAX_IMPORTS];
static unsigned g_hle_count;

/* Результат импорта, который видит гость.
 *
 * Сигнала здесь нет вовсе: трамплин внутри отображения гостя вызывает эту
 * функцию обычным `jalr`, поэтому ни один регистр гостя не страдает. Это и
 * было целью: через `break` терялись `$k0` и `$k1`, а гость использует `$k0`
 * как входной параметр.
 *
 * `args[0..3]` — `$a0`..`$a3` гостя, `args[4..6]` — три аргумента из его стека
 * вызова. */
/* Адрес структуры сведений о потоке, видимый гостю.
 *
 * Располагается в отображении гостя, после пула трамплинов: там уже есть
 * свободное место, адрес принадлежит гостю, и по нему гость может писать.
 * Хостский адрес не годится — гость трактует его как свой.
 *
 * Структура заполняется один раз, при первом обращении. Из разбора гостя
 * известно, что он пишет по смещению 4 (`0x08ABD018  sw s5,4(k0)`), то есть
 * начало структуры — указатель на его собственный блок памяти. Этот указатель
 * берётся из аргумента `CpuSuspendIntr`, который гость передаёт как `$a1`.
 *
 * Возвращает 0, если отображение гостя недоступно: выдавать гостю нечитаемый
 * адрес хуже, чем признать неудачу. */
static u32 g_thread_info_addr(const u32 *args)
{
    volatile u32 *p;

    if (g_thread_info != 0)
        return g_thread_info;
    if (g_mod.memory == NULL || g_mod.tramp_base == 0)
        return 0;
    g_thread_info = g_mod.tramp_base + GUEST_TRAMP_SIZE - THREAD_INFO_BYTES;
    p = (volatile u32 *)(uintptr_t)g_thread_info;
    /* Смещение 4 — указатель гостя на его собственный блок памяти. Известен
     * только из аргументов импорта, поэтому при `args == NULL` (запуск потока)
     * поле остаётся нулём, а не разыменовывается. */
    p[0] = (args != NULL) ? args[1] : 0;
    p[1] = 0;
    p[2] = 0;
    p[3] = 0;
    return g_thread_info;
}

u32 hle_import(u32 index, const u32 *args, u32 k0, u32 ra)
{
    u32 nid;

    if (index >= g_hle_count)
        return 0;
    nid = g_hle_nid[index];

    g_state->calls++;
    if (g_state->calls <= STUB_LOG_SIZE) {
        /* Логируется ИНДЕКС, а не NID.
     *
     * Индекс — ключ ко всему: по нему восстанавливается и NID
     * (`g_hle_nid[index]`), и номер трамплина в пуле
     * (`tramp_base + index * GUEST_TRAMP_BYTES`), а значит и адрес стаба в
     * госте. По NID обратного перехода нет: одна и та же функция встречается в
     * нескольких библиотеках, и по её названию адрес в госте не находится.
     *
     * Именно этого не хватало для разбора падения: было известно, что поток
     * остановился на стабе `0x08AD2E4C`, а сопоставить его с вызовом в отчёте
     * было нечем — индексов в списке не было. */
    g_state->stubs[g_state->calls - 1] = index;
        if (g_state->calls <= CTX_DUMP_TRAPS) {
            unsigned t = (unsigned)g_state->calls - 1;

            g_state->args[t][0] = args[0];
            g_state->args[t][1] = args[1];
            g_state->args[t][2] = args[2];
            g_state->args[t][3] = args[3];
            g_state->args[t][4] = args[4];
            g_state->args[t][5] = args[5];
            g_state->args[t][6] = args[6];
            g_state->args[t][7] = k0;
            /* pid обязателен: без него не видно, какой из потомков сделал
             * вызов. Счётчик общий для обоих, и по номеру вызова это не
             * определить — а от этого зависит, чей `$k0` наблюдается. */
            g_state->args[t][8] = (u32)getpid();
            g_state->args[t][9] = ra;   /* адрес возврата = место вызова */
            g_state->args[t][10] = args[-2];  /* $sp+0 трамплина: сохранённый $ra */
            g_state->args[t][11] = args[-1];  /* $sp+4: промежуток кадра */
            /* Весь кадр трамплина подряд, `$sp-32` .. `$sp+60`.
             *
             * Нужно потому, что разбор по слотам дал невозможное: в слот
             * `+12` положен `$a2`, а в отчёте на его месте стоит `$ra`, при
             * том что соседние слоты верны. Значит либо адрес, который C
             * считает за `args`, не тот, либо раскладка кадра не та, и
             * вывод по одному-двум слотам этого не различает. Разбор всего
             * кадра различает сразу. */
            {
                int f;
                for (f = -8; f < 16; f++)
                    g_state->frame[t][f + 8] = args[f];
            }
        }
    } else {
        g_state->log_overflow++;
    }

    /* Потоки: единственные импорты, где результат важен и где он не ноль.
     * Настоящего планировщика нет — функция потока запускается родителем
     * после возврата гостя из точки входа, отдельным потомком. */
    if (nid == 0x446D8DE6u) {
        g_state->thread_entry = args[1];
        return 1;
    }
    if (nid == 0xF475845Du) {
        g_state->thread_started = 1;
        return 0;
    }

    /* GetModuleIdByAddress возвращает УКАЗАТЕЛЬ на структуру сведений о потоке.
     *
     * Возврат нуля здесь стоил SIGSEGV в потоке гостя. Локализовано разбором
     * загруженного кода: `0x08ABD018  sw s5,4(k0)` пишет по `$k0`, а `$k0`
     * равен нулю — в отчёте о сбое именно `k0=0`, `si_addr=0`, `SIGSEGV`.
     * Наполнить `$k0` кодом гостя не может: разобрано 2 КиБ функций потока и
     * `0x08AA6A10`, записи в `$k0` нет ни в одной. То есть значение приходит
     * через возвращаемое значение импорта.
     *
     * Адрес структуры берётся из отображения гостя, а не из хоста: гость
     * будет по нему читать и писать, и хостский адрес для него бессмыслен. */
    if (nid == 0xD8B73127u) {
        if (!g_thread_info_off)
            return g_thread_info_addr(args);
        return 0;
    }

    if (!is_implemented(nid))
        g_state->unknown++;
    return 0;
}

/* Значение `$gp`, которое вычислит пролог `hle_import`.
 *
 * Берётся чтением самого пролога, а не вычислением по формуле: формула
 * зависит от того, какие пары `lui`/`addiu` компилятор выбрал для `$gp`, и
 * изменение флагов сборки её бы тихо сломало. Пролог проверяется по опкодам,
 * и при несовпадении подстановка не выполняется вовсе — молча передать
 * гостю мусор в `$gp` хуже, чем отказаться. */
static bool gp_value(u32 fn, u32 *out)
{
    const u32 *p = (const u32 *)(uintptr_t)fn;
    u32 w0 = p[0], w1 = p[1], w2 = p[2];
    u32 hi, lo;

    /* lui $gp,imm ; addiu $gp,$gp,imm ; addu $gp,$gp,$t9 */
    if ((w0 & 0xFFFF0000u) != 0x3C1C0000u)
        return false;
    if ((w1 & 0xFFFF0000u) != 0x279C0000u)
        return false;
    if (w2 != 0x0399E021u)
        return false;
    hi = w0 & 0xFFFFu;
    lo = w1 & 0xFFFFu;
    /* `addiu` расширяет непосредственный операнд знаком: без этого gp
     * получался на 0x10000 больше, и GOT-слот читался не оттуда. */
    *out = (hi << 16) + (u32)(int32_t)(int16_t)(u16)lo + fn;
    return true;
}

/* Ставит трамплины на место ловушек: каждый стаб начинает звать хостскую
 * функцию напрямую, без сигнала и без промежуточного состояния. */
static bool install_trampolines(u32 host_fn, u32 host_gp)
{
    u32 li, ii;
    u32 index = 0;

    g_hle_count = 0;
    for (li = 0; li < g_imports.count; li++) {
        for (ii = 0; ii < g_imports.libs[li].count; ii++) {
            GuestStubPatch patch;

            if (index >= HLE_MAX_IMPORTS) {
                snprintf(g_mod.error, sizeof(g_mod.error),
                         "слишком много импортов: %u", index);
                return false;
            }
            patch.target = host_fn;
            patch.stub = g_imports.libs[li].imports[ii].stub_runtime;
            /* Последний аргумент — адрес `SceThreadContext`, который трамплин
             * устанавливает в `$k0` при каждом возврате в гостя. Здесь он
             * равен нулю: самостоятельный инструмент тратится на дампы
             * образа, а не на исполнение гостя. */
            if (!guest_build_import_trampoline(&g_mod, &patch, host_fn, host_gp,
                                               index,
                                               (u32)(uintptr_t)&g_state->tramp_done,
                                               0))
                return false;
            g_hle_nid[index] = g_imports.libs[li].imports[ii].nid;
            index++;
        }
    }
    g_hle_count = index;

    /* Адреса стабов потоков больше не нужны: обработчика ловушки нет, роль
     * разыгрывает hle_import. */
    g_state->stub_create_thread = 0;
    g_state->stub_start_thread = 0;

    guest_flush_icache(g_mod.memory, g_mod.map_size);
    return true;
}

static void install_handlers(void)
{
    struct sigaction sa;
    int sigs[3];
    int i;

    /* altstack не регистрируется и SA_ONSTACK не ставится: обработчик сбоя
     * работает на прерванном стеке, а он у гостя всегда отображён.
     *
     * Импорты больше не идут через сигналы вовсе — их зовут хостские функции
     * трамплинами, минуя сигнальный механизм целиком. Именно это и было
     * целью: через `break` терялись `$k0` и `$k1`, а гость использует `$k0`
     * как входной параметр. */

    memset(&sa, 0, sizeof(sa));

    /* SA_NODEFER здесь недопустим.
     *
     * Если обработчик ловушки не выходит сразу или ловушка срабатывает
     * снова до возврата, разрешение вложенности даёт неограниченный рост
     * числа кадров сигналов. Кадр растёт вниз, и при исчерпании отведённой
     * памяти ядро убивает процесс SIGSEGV — с адресом в области стека, что
     * и наблюдалось: si_addr был выше вершины гостевого стека.
     *
     * Без SA_NODEFER повторный сигнал того же вида ставится в очередь и не
     * порождает вложенности. */
    sa.sa_flags = SA_SIGINFO;
    sigaction(SIGTRAP, &sa, NULL);

    sa.sa_sigaction = guest_fault;
    /* Для диагностического обработчика вложенность нужна: иначе сбой внутри
     * него приведёт к глухому зависанию на сигнале по умолчанию. */
    sa.sa_flags = SA_SIGINFO | SA_NODEFER;
    for (i = 0; i < 3; i++) {
        sigs[i] = (i == 0) ? SIGSEGV : (i == 1) ? SIGBUS : SIGILL;
        sigaction(sigs[i], &sa, NULL);
    }
}

