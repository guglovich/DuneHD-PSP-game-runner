struct run_state {
    /* Индекс поля с адресом инструкции в ucontext. Находит его потомок,
     * читает родитель, поэтому -1, а не 0: значение 0 означало бы «найдено
     * поле gregs[0]», а это вовсе не так. */
    volatile int pc_index;

    /* Что увидел обработчик. */
    volatile int trap_outside_stubs;  /* ловушка сработала вне области стабов */
    volatile int trap_pc_unresolved;  /* адрес инструкции найти не удалось */

    volatile unsigned long calls;      /* всего вызовов импортов */
    volatile unsigned long unknown;     /* из них без реализации */
    volatile unsigned long log_overflow;

    volatile unsigned fault_sig;
    volatile u32         fault_addr;

    /* Регистры сбоя целиком. Поиск «первого регистра в диапазоне гостя»
     * даёт правдоподобный, но неверный ответ: первым в диапазоне может
     * оказаться $ra или $t9, а не адрес инструкции. Замер на плеере показал,
     * что поле PC — это gregs[25], и читать надо именно его, а не угадывать. */
    /* Ровно 32: gregs[] содержит 32 элемента, и чтение 32..34 — выход за
     * массив. Это не теория: компилятор выдаёт на такой цикл
     * «iteration 32 invokes undefined behavior», и мусор оттуда попадал бы
     * в диагностику сбоя как «регистр гостя». */
    volatile u32         regs[40];
    volatile int         regs_valid;
    /* Все три смещения, где PC встречается в кадре. Печатаются ВСЕ: вывод
     * делается по одному полю, а если оно по какой-то причине не PC, то
     * это видно только когда напечатаны все три. */
    volatile u32         pc_offs[3];   /* диагностика: +0x20, +0x40, +0xF0 */

    /* Проход по стеку гостя на момент сбоя: адреса возврата и смещения, на
     * которых они лежат. Заполняется прямо в обработчике. */
#define BT_MAX       24
#define BT_SCAN_WORDS 512
    volatile u32         bt[BT_MAX];
    volatile u32         bt_word[BT_MAX];
    volatile int         bt_count;

    /* Индекс последнего импорта, чей трамплин ВЕРНУЛСЯ в гостя. Заполняется
     * трамплином непосредственно перед `jr $ra`: разделяемая страница, иначе
     * потомку не передать. Отвечает прямо на вопрос «падает ли гость внутри
     * трамплина или уже в своём коде». */
    volatile u32         tramp_done;

    /* Стадия потомка: без неё сбой в хостовом коде и сбой гостя выглядят
     * одинаково, потому что обработчик один на оба. */
    volatile unsigned long child_pid;
    volatile int         child_stage;
    volatile unsigned long fault_pid;
    volatile u32         guest_reg_hit;   /* что нашлось перебором */
    volatile int         guest_reg_index;

    /* Индексы последних вызванных импортов. По индексу восстанавливаются NID,
     * адрес трамплина и адрес стаба в госте, то есть по нему можно найти
     * место в разобранном коде гостя. */
    volatile u32 stubs[STUB_LOG_SIZE];

    /* Вход в обработчик и аргумент контекста.
     *
     * Разбор одного дампа сбоя дал противоречивые числа: адрес сбоя совпал с
     * первой инструкцией `import_trap`, но первая инструкция — это `lui`, а она
     * не может дать SIGSEGV, и вычисленный из неё `$gp` не сходился с
     * напечатанным. Значит одно из двух чисел относится не к тому месту, и
     * угадывать нельзя. Счётчик и указатель контекста снимают вопрос фактом:
     * `traps_entered` > 0 означает, что ловушка дошла до обработчика. */
    volatile unsigned long traps_entered;
    volatile u32         trap_ctx;

    /* Смещение в байтах от начала ucontext, где лежит адрес сработавшей
     * инструкции.
     *
     * Найти его перебором по gregs[] не вышло: адрес стаба не совпал ни с
     * одним элементом, то есть раскладка ucontext на этой прошивке не та,
     * что предполагает заголовок musl. Искать поле по номеру означало бы
     * угадывать, а исход адреса ловушки известен точно — значит, поле надо
     * найти фактом, сравнением с адресом стаба. Сканируется ровно
     * STUB_SCAN_BYTES байт контекста. */
    volatile int         trap_stub_off;
    volatile u32         trap_stub_seen;

    /* Поток гостя.
     *
     * Адреса стабов известны заранее (их находит родитель при загрузке), а
     * обработчик не может вызвать ни одной функции — `$t9` равен 0. Поэтому
     * сопоставление «стаб -> роль» делается сравнением двух чисел, а поиск
     * импорта по NID остаётся в родителе.
     *
     * Поле `thread_entry` берётся из `$a1`, а не из `$a2`: на этой игре
     * `sceKernelCreateThread` вызывается как (имя, функция, размер_аргумента,
     * размер_стека, ...). Замер: $a0 = 0x08ACBBC8 — строка имени в .rodata,
     * $a1 = 0x08ABCF68 — адрес в тексте гостя, $a2 = 0x20, $a3 = 0x19000 =
     * 102400 байт стека. Ни один аргумент, кроме $a1, на код не похож. */
    volatile u32         stub_create_thread;
    volatile u32         stub_start_thread;
    volatile u32         thread_entry;
    volatile int         thread_started;
    volatile int         thread_ran;

    /* Регистры вызова при первых ловушках, поимённо.
     *
     * Смещения измерены пробой tests/uctx_layout.c, а не взяты из заголовка:
     * поиск перебором по gregs[] на плеере даёт нули, значит раскладка не та,
     * что подразумевает musl. Прежний вывод «gregs[2] — это не $v0» был
     * неверен: измерение показало, что это именно $v0. */
    /* a0, a1, a2, a3 и три аргумента из стека вызова гостя. Стек — 7 слов:
     * трамплин читает их по `$sp + 80/84/88` и передаёт в `hle_import`
     * вместе с четырьмя регистровыми. */
    /* Снимок аргументов: [0..3] — `$a0..$a3`, [4..6] — стековые,
     * [7] — `$k0`, [8] — pid, [9] — `$ra`.
     *
     * [10] и [11] — «сырые» слова кадра трамплина ДО `args[0]`, то есть
     * `$sp+0` и `$sp+4`. Сняты потому, что замер показал нестыковку, которую
     * рассуждением не разрешить: и `$a1`, и `$ra` в отчёте завышены на 4,
     * а `$a0`, `$a2`, `$a3` верны. Слово по адресу `args[-2]` — это сохранённый
     * `$ra`, то есть эталон, с которым можно сверить всё остальное, не гадая. */
    volatile u32         args[CTX_DUMP_TRAPS][12];

    /* Весь кадр трамплина: индекс `f+8` соответствует смещению `f*4` байт
     * от `$sp` гостя, то есть 0 — это `args[0]`. Заполняется прямо в
     * обработчике импорта; печатается для первых CTX_DUMP_TRAPS вызовов. */
    volatile u32         frame[CTX_DUMP_TRAPS][24];

    /* Снимок ucontext при первых ловушках.
     *
     * Раскладка контекста на этой прошивке не совпадает с той, что подразумевает
     * заголовок musl: адрес инструкции найден на 32 байтах от начала, а не в
     * gregs[], поэтому и `$v0`, и `$a0`–`$a3` по номерам элементов читать
     * нельзя. Снимок снимает вопрос фактом: значения, похожие на адреса, сразу
     * видно, и поле узнаётся по тому, что содержит ожидаемое. */
    volatile u32         ctxdump[CTX_DUMP_TRAPS][CTX_DUMP_WORDS];
    volatile int         ctxdump_n;

    /* Слова инструкции по адресу сбоя. Адрес указывает внутрь нашего образа,
     * поэтому четыре слова читаются безопасно и показывают ту инструкцию,
     * на которой процессор остановился. */
    volatile u32         insn[4];
    volatile int         insn_valid;
    /* 0 — адрес не наш и не гостевой, 1 — наш образ, 2 — гость. */
    volatile int         insn_where;
};

